function asset(bytes,extension,type){
 bytes=Buffer.from(bytes);return {path:'assets/'+createHash('sha256').update(bytes).digest('hex')+'.'+extension,bytes,contentType:type};
}
test('plots from the publication renderer supply an individually identifiable, content-addressed SVG',async()=>{
 const {book,record}=selectionBook();record.sections=[];const plot=createFigure();plot.title='Sampling variance';
 plot.series[0].points=[{x:0,y:14,error:null},{x:1,y:17,error:null}];assert.ok(validFigure(plot));
 record.figures=[plot];const converted=await convertPublicationRecord({},book,record);
 const descriptors=converted.assets.map(a=>({name:a.path,contentType:a.contentType,sha256:a.path.slice(7,71)}));
 const figure=sourceGalleryItems(converted.html,descriptors).get('figure:'+plot.id);
 assert.equal(figure?.kind,'graph');assert.equal(figure.caption,'Sampling variance');assert.match(figure.asset,/\.svg$/);
});

