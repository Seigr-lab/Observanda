const document=body=>'<html><head><title>Report</title></head><body><main>'+body+'</main></body></html>';
async function setup(t){
 const root=await mkdtemp(path.join(os.tmpdir(),'observanda-site-style-'));await mkdir(path.join(root,'.observanda'));
 t.after(async()=>{await closeIdleMutationFiles();await rm(root,{recursive:true,force:true,maxRetries:10});});
 const ws=new Workspace(root,{id:randomUUID(),key:randomBytes(32)}),id=randomUUID(),store=new WebsiteFileStore(ws);
 ws.openCatalogue=ws.catalogue=()=>assert.fail('Saved website opened research storage');
 let result=await store.importFiles(id,{name:'Atlas',files:new Map([['index.html',document('<h1>Home</h1>')],['lab/run.html',document('<h1>Report</h1><section><p>Units</p></section>')],['style.css','main { max-width: 72ch; }']]),draftFiles:new Map([['lab/private.html',document('<p>Working</p>')],['draft-styles.css','']])});
 return {id,store,get revision(){return result.site.revision;},accept:r=>(result=r),
  change:async(action,options={})=>{const r=await websiteStyleBook(store,id,{action,expectedRevision:result.site.revision,path:'lab/run.html',...options});if(r.site)result=r;return r;}};
}
test('site style assignments drive only referenced public resources, keep private fonts private and preserve component and design ownership',async t=>{
 const w=await setup(t),{store,id,change}=w;
 const create=async(name,group,rules)=>(await change('create',{name,group,rules})).modifiedStyleId;
 const body=await create('Body typography','typography',{normal:{'font-family':'atkinson','font-size':'18px'},print:{'font-size':'12px'}});
 await change('assign',{group:'typography',tokenId:body,scope:'site'});
 const stock=BUNDLED_FONTS.find(f=>f.id==='atkinson');
 let out=await store.publicationInventory(id,{expectedRevision:w.revision});
 for(const face of stock.faces)assert.ok(out.files.includes('fonts/'+face.file));
 assert.ok(out.files.includes('fonts/'+stock.license));
 const paint=await create('Culture accent','color',{normal:{color:'#114466'},hover:{color:'#7600cc'},'focus-visible':{color:'#517502'}});
 const local=await create('Private chart legend','color',{normal:{color:'#f014ab'}});
 await change('assign',{tokenId:local,group:'color',scope:'page',path:'lab/private.html'});
 await change('assign',{tokenId:paint,group:'color',scope:'element',blockPath:'0/1'});
 out=await store.publicationInventory(id,{expectedRevision:w.revision});
 assert.ok(!out.files.includes(styleResource(local)));assert.ok(out.files.includes(styleResource(paint)));
 const opened=await store.open(id,{path:'lab/run.html'});
 assert.match(opened.html,new RegExp('ow-token-'+paint));
 const home=await store.open(id);assert.equal(home.html.includes(paint),false);
 const changeMain=await componentOperation(store,'create',id,{path:'lab/run.html',expectedRevision:w.revision,name:'Legend',blockPath:'0/1'});w.accept(changeMain);
 const {items:[main]}=await componentOperation(store,'list',id,{path:'lab/run.html',expectedRevision:w.revision});
 const spacing=await create('Inset','spacing',{normal:{'padding-inline':'2rem'}});
 await change('assign',{tokenId:spacing,group:'spacing',scope:'component',component:main.id});
 assert.ok((await store.open(id,{path:'lab/run.html'})).html.includes('ow-token-'+spacing));
 const design=(action,values)=>websitePageDesigns(store,id,{action,path:'lab/run.html',expectedRevision:w.revision,...values});
 w.accept(await design('name',{name:'Plate'}));const {items:[d]}=await design('list',{});
 w.accept(await design('use',{design:d.id,title:'Cell culture',destination:'analysis/culture.html',inclusion:'included',labels:{text:'Text',heading:'New heading',image:'Image'}}));
 assert.ok((await store.open(id,{path:'analysis/culture.html'})).html.includes('ow-token-'+spacing));
 await change('remove',{tokenId:spacing});
 const now=await store.open(id,{path:'analysis/culture.html'});
 assert.equal(now.html.includes(styleResource(spacing)),false);
 w.accept(await store.save(id,{expectedRevision:w.revision,path:now.path,html:now.html,css:now.css}));
 const encoded=bundledFonts.get('fonts/'+stock.faces[0].file).toString('base64');
 await assert.rejects(change('import-font',{encoded,embed:true,rights:'open-license'}),{code:'INVALID'});
 const font=(await change('import-font',{encoded,embed:true,rights:'open-license',notice:'Public font notice for this test.'})).importedFontId;
 const custom=await create('Licensed body','typography',{normal:{'font-family':font}});
 await change('assign',{group:'typography',tokenId:custom,scope:'page'});
 out=await store.publicationInventory(id,{expectedRevision:w.revision});
 assert.ok(out.files.includes('licenses/'+font+'.txt'));assert.ok(out.files.some(f=>f.startsWith('fonts/'+font)));
 const edition=await WebsiteFilesCandidate.open(store,id,w.revision,{blockedValues:['Redistribution','notice for this test']});await assert.rejects(edition.verify(),{code:'PRIVACY'});
 const historical=(await websiteVersions(store,id,'list',{expectedRevision:w.revision})).items[0].id;
 await change('update',{tokenId:custom,name:'Licensed body',rules:{normal:{'font-family':'system-ui'}}});
 await change('font-rights',{fontId:font,embed:false,rights:'open-license'});
 const restore={kind:'styleBook',version:historical,expectedRevision:w.revision};
 const restorePlan=await websiteVersionDesign(store,id,restore);assert.equal(restorePlan.status,'ready');assert.ok(restorePlan.total>0);
 w.accept(await websiteVersionDesign(store,id,{...restore,reviewId:restorePlan.reviewId},true));
 out=await store.publicationInventory(id,{expectedRevision:w.revision});assert.ok(!out.files.some(f=>f.includes(font)));
});

test('an update to a private page style leaves an unrelated public canvas mounted and skips unrelated HTML reads',async t=>{
 const w=await setup(t),{id,store,change}=w;
 const privatePath='lab/private.html',style=(await change('create',{group:'color',name:'Working legend',rules:{normal:{color:'#112233'}}})).modifiedStyleId;
 await change('assign',{path:privatePath,scope:'page',group:'color',tokenId:style});
 const before=await store.open(id),reads=[],read=store.readText.bind(store);
 store.readText=(file,options)=>{if(file.name?.endsWith('.html'))reads.push(file.name);return read(file,options);};
 await change('update',{path:privatePath,tokenId:style,name:'Working legend',rules:{normal:{color:'#223344'}}});
 const status=await store.versionStatus(id,{expectedRevision:before.site.revision,path:'index.html'});
 assert.equal(status.surfaceStamp,before.surfaceStamp);
 assert.ok(reads.every(name=>name===privatePath),'editing one private style re-read '+reads.join(', '));
});

test('moved pages preserve explicit styles, inherit the new folder and duplication uses independently owned definitions',async t=>{
 const w=await setup(t),{store,id,change}=w;
 const folderStyle=(await change('create',{group:'spacing',name:'Instrument rows',rules:{normal:{gap:'9px'}}})).modifiedStyleId;
 const pageStyle=(await change('create',{group:'layout',name:'Plate columns',rules:{normal:{display:'grid','grid-template-columns':'repeat(3, minmax(0, 1fr))'}}})).modifiedStyleId;
 await change('assign',{scope:'folder',group:'spacing',tokenId:folderStyle});await change('assign',{scope:'page',group:'layout',tokenId:pageStyle});
 await change('assign',{scope:'element',blockPath:'0/1',group:'spacing',tokenId:folderStyle});
 const authored=await store.open(id,{path:'lab/run.html'}),override='\n.ow-token-'+folderStyle+' > p { text-decoration: underline; }';
 w.accept(await store.save(id,{expectedRevision:w.revision,path:authored.path,html:authored.html,css:authored.css+override}));
 const move={expectedRevision:w.revision,path:'lab/run.html',action:'move',destination:'reports/run.html'};
 const review=await websitePageLifecycle(store,id,move);
 w.accept(await websitePageLifecycle(store,id,{...move,reviewId:review.reviewId},true));
 const moved=await store.open(id,{path:move.destination});
 assert.ok(moved.html.includes('data-website-page-styles="'+pageStyle+'"'));assert.ok(!moved.html.includes('data-website-folder-styles'));
 const sourceRevision=w.revision,siteCopy={expectedRevision:sourceRevision,action:'duplicate',title:'Independent protocol',copyId:randomUUID()};
 const copyReview=await websiteSiteLifecycle(store,id,siteCopy);
 const duplicate=await websiteSiteLifecycle(store,id,{...siteCopy,reviewId:copyReview.reviewId},true);
 const newPage=await store.open(siteCopy.copyId,{path:move.destination});
 const copied=await websiteStyleBook(store,siteCopy.copyId,{expectedRevision:duplicate.site.revision,path:move.destination,action:'list'});
 const own=copied.items.find(t=>t.name==='Plate columns'),ownSpacing=copied.items.find(t=>t.name==='Instrument rows');
 assert.notEqual(own.id,pageStyle);assert.notEqual(ownSpacing.id,folderStyle);
 assert.equal(own.classId,pageStyle);assert.equal(ownSpacing.classId,folderStyle);
 assert.ok(newPage.html.includes(own.classId)&&newPage.html.includes('ow-token-'+ownSpacing.classId));assert.ok(newPage.css.includes(override));
 await websiteStyleBook(store,siteCopy.copyId,{action:'update',expectedRevision:duplicate.site.revision,path:move.destination,tokenId:own.id,name:own.name,rules:{normal:{display:'block'}}});
 assert.equal((await store.open(id,{path:move.destination})).site.revision,sourceRevision);
});
