import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,realpath,stat} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {encryptedFixture} from './browser/encrypted-fixture.js';
import {sampleNotebook} from '../src/sample.js';
import {ResearchMaterials} from '../src/research-materials.js';
import {clearVault} from '../src/encryption.js';
import {defaultColumn} from '../src/web/dataset-schema.js';
import {datasetExchangeSelection,delimitedDataset} from '../src/dataset-exchange-table.js';
import {datasetExchangeJSONL} from '../src/dataset-exchange-jsonl.js';
import {readDatasetExchange} from '../src/dataset-exchange-reader.js';
import {exchangeDelimitedRendition,exchangeManifest} from '../src/dataset-exchange-renditions.js';
import {digest} from '../src/storage-format.js';
import {unzipSync} from 'fflate';
import {randomUUID} from 'node:crypto';
import {prepareExchangeFiles,exchangeArchive,removeExchangeAttempt} from '../src/dataset-exchange-files.js';
import {withDatasetExchangeAuthority} from '../src/dataset-exchange-authority.js';

test('a pinned native dataset exchanges exact and missing values with its selected source addresses', {timeout:180000},async t=>{
 const parent=await realpath(os.tmpdir()),directory=await mkdtemp(path.join(parent,'observanda-exchange-'));
 const notebook=sampleNotebook(),fixture=await encryptedFixture(directory,notebook);
 t.after(async()=>{
  await clearVault(fixture.vault);assert.equal(path.dirname(directory),parent);
  await rm(directory,{recursive:true,force:true,maxRetries:4,retryDelay:100});
 });
 const materials=new ResearchMaterials(fixture.workspace),recordId=notebook.entries[0].id;
 const names=['counter','rate','native','missing','withheld','blank','notes'];
 const long='x'.repeat(16383)+'🌱'+', a quoted "value"';
 const line=JSON.stringify({counter:'9007199254740993',rate:'2/7',native:'11.3',missing:null,blank:'',notes:long});
 const bytes=Buffer.from(line+'\n'+line),upload=await materials.startImport({recordId,name:'readings.jsonl',size:bytes.length});
 await materials.appendImport(upload.id,0,[bytes]);const artifact=await materials.finishImport(upload.id);
 const declared=['integer','rational','radix-fraction','text','text','text','text'];
 const sourceMapping={format:'jsonl',fields:names.map(name=>({name,path:'/'+name}))};
 const columns=names.map((label,index)=>({...defaultColumn({label}),representation:declared[index],radix:index===2?6:10}));
 const result=await materials.dataset({recordId,title:'Retained readings',artifact,sourceMapping,columns,exclusions:{[artifact.id+':2']:'Instrument stopped'}});
 const doc=await materials.read(result),ref={kind:'dataset',id:result.id,revision:result.revision,workspaceId:notebook.id};
 const selection=datasetExchangeSelection(doc,{offset:0,count:null,columns:null,includeExcluded:true});
 const options={signal:t.signal,check:async()=>{},checkSource:source=>materials.checkReference(source)};
 const wire=()=>datasetExchangeJSONL(materials,doc,ref,selection,options);
 const found=new Map();let row,field,firstRow,secondRow;
 const exportedSources=[];
 const receipt=await readDatasetExchange(wire(),async frame=>{
  if(frame.type==='source')exportedSources.push(frame.ref);
  if(frame.type==='row'){row=frame.index;if(!row)firstRow=frame.metadata;else secondRow=frame.metadata;}
  if(row===0&&frame.type==='cell'){field={kind:frame.properties.kind,text:frame.text??''};found.set(frame.index,field);}
  if(row===0&&frame.type==='text')field.text+=frame.text;
 },{signal:t.signal});
 assert.deepEqual([receipt.rows,receipt.columns,receipt.cells],[2,7,14]);
 assert.deepEqual(names.map((_,i)=>found.get(i).text),['9007199254740993','2/7','11.3','','','',long]);
 assert.deepEqual([3,4,5].map(i=>found.get(i).kind),['null','absent','string']);
 assert.equal(firstRow.id,artifact.id+':1');assert.equal(secondRow.excluded,'Instrument stopped');
 assert.ok(exportedSources.some(source=>source.id===artifact.id&&source.revision===artifact.revision&&source.workspaceId===notebook.id));
 let csv='';for await(const chunk of delimitedDataset(materials,doc,{...selection,includeExcluded:false},{...options,format:'tsv'}))csv+=chunk;
 assert.ok(csv.includes('"9007199254740993"\t"2/7"\t"11.3"'));assert.equal(csv.split('\r\n').length,3);
 const transfer=[];for await(const part of wire())transfer.push(part);
 let rendered='';for await(const piece of exchangeDelimitedRendition(transfer,'tsv'))rendered+=piece;
 let direct='';for await(const piece of delimitedDataset(materials,doc,selection,{...options,format:'tsv'}))direct+=piece;
 assert.equal(rendered,direct);
 const original=Buffer.concat(transfer),typed={size:original.length,sha256:digest(original)},delimited={size:Buffer.byteLength(rendered),sha256:digest(rendered)};
 const manifest=[];for await(const part of exchangeManifest(transfer,{format:'tsv',typed,delimited}))manifest.push(JSON.parse(part));
 assert.equal(manifest.find(f=>f.type==='dataset').ref.revision,ref.revision);
 assert.equal(manifest.filter(f=>f.type==='column').length,7);
 assert.equal(manifest.filter(f=>f.type==='row'||f.type==='cell').length,0);
 assert.deepEqual(manifest.at(-2).files.map(file=>file.sha256),[typed.sha256,delimited.sha256]);
 const incomplete=transfer.slice(0,-1);
 await assert.rejects(readDatasetExchange(incomplete,()=>{}),{code:'MATERIAL_INVALID'});
 const altered=Buffer.concat(transfer);
 altered[altered.indexOf('9007199254740993')+15]=50;
 await assert.rejects(readDatasetExchange([altered],()=>{}),{code:'MATERIAL_INVALID'});
 const projection=datasetExchangeSelection(doc,{offset:0,count:2,columns:[{offset:0,count:1}],includeExcluded:false});
 const projected=[];
 for await(const part of datasetExchangeJSONL(materials,doc,ref,projection,options))projected.push(part);
 const compact=Buffer.concat(projected),summary=await readDatasetExchange([compact],()=>{});
 assert.deepEqual([summary.rows,summary.columns],[1,1]);
 for(const omitted of ['Instrument stopped','/notes','"missing"\u003a"null"','2/7','11.3',long])assert.ok(!compact.includes(omitted));
 const otherBytes=Buffer.from('Pair,Internal note\n9007199254740993,Unshared laboratory note\n');
 const otherUpload=await materials.startImport({recordId,name:'joined.csv',size:otherBytes.length});
 await materials.appendImport(otherUpload.id,0,[otherBytes]);const otherArtifact=await materials.finishImport(otherUpload.id);
 const joined=await materials.dataset({recordId,title:'Private lab notes',artifact:otherArtifact,columns:[{...defaultColumn({label:'Pair'}),representation:'integer'},defaultColumn({label:'Internal note'})]});
 const calculation={version:2,source:result,projection:[0],view:'observations',joins:[{dataset:joined,projection:[0,1],keys:[{left:0,right:0}],where:null,unmatched:'error'}],steps:[],where:null,selectionReason:'',calibration:null,note:'Internal observations'};
 const combined=await materials.dataset({recordId,title:'Combined observations',calculation}),combinedDoc=await materials.read(combined);
 const combinedRef={kind:'dataset',id:combined.id,revision:combined.revision,workspaceId:notebook.id};
 const selected=datasetExchangeSelection(combinedDoc,{offset:0,count:null,columns:[{offset:0,count:1}],includeExcluded:false});
 const granted=new Set(),fragments=[];
 const scoped={...options,checkSource:async pin=>{granted.add(pin.id);return materials.checkReference(pin);}};
 for await(const part of datasetExchangeJSONL(materials,combinedDoc,combinedRef,selected,scoped))fragments.push(part);
 const partial=Buffer.concat(fragments);
 assert.ok(granted.has(joined.id),'the omitted join still participates in the access decision');
 assert.ok(partial.includes(result.revision),'the selected observation keeps its source revision');
 for(const withheld of [joined.id,joined.revision,'Internal note','Unshared laboratory note','Internal observations'])assert.ok(!partial.includes(withheld));
 const job=randomUUID(),attempt=randomUUID(),command={recordId,ref,format:'tsv',selection};
 const interrupted=randomUUID(),stop=new AbortController();
 await assert.rejects(withDatasetExchangeAuthority(materials,command,{signal:stop.signal},(doc,grants)=>prepareExchangeFiles(materials,doc,command,{job,attempt:interrupted,...grants,progress:()=>stop.abort()})),{name:'AbortError'});
 await assert.rejects(stat(path.join(fixture.workspace.root,'.observanda','materials','exchanges',job,interrupted)),{code:'ENOENT'});
 const prepared=await withDatasetExchangeAuthority(materials,command,options,(doc,guards)=>prepareExchangeFiles(materials,doc,command,{job,attempt,...guards}));
 const downloaded=[];
 await withDatasetExchangeAuthority(materials,command,options,async(_doc,guards)=>{
  for await(const part of exchangeArchive(fixture.workspace,job,prepared,guards))downloaded.push(part);
 });
 const zip=unzipSync(Buffer.concat(downloaded));
 assert.deepEqual(Object.keys(zip).sort(),['dataset.jsonl','dataset.tsv','manifest.jsonl']);
 assert.equal(Buffer.from(zip['dataset.tsv']).toString(),direct);
 assert.equal(digest(zip['dataset.jsonl']),typed.sha256);
 const originalTransfer=await materials.startImport({recordId,name:'dataset.jsonl',size:original.length});
 await materials.appendImport(originalTransfer.id,0,[original]);
 const received=await materials.finishImport(originalTransfer.id);
 const imported=await materials.dataset({recordId,title:'Imported research observations',artifact:received,exchangeImport:1});
 const restored=await materials.read(imported),restoredRows=await materials.datasetPage(imported,0,{columnOffset:0,columnLimit:7});
 assert.equal(restored.content.exchangeOrigin.sha256,receipt.sha256);
 assert.equal(restored.content.exchangeOrigin.ref.revision,ref.revision);
 assert.deepEqual(restored.content.exchangeOrigin.ref,{datasetId:ref.id,workspaceId:notebook.id,revision:ref.revision});
 assert.equal(restoredRows.rows.length,2);
 assert.equal(restoredRows.rows[0].id,firstRow.id);
 assert.equal(restoredRows.rows[1].excluded,secondRow.excluded);
 assert.deepEqual(restoredRows.rows[0].cells.slice(0,6),['9007199254740993','2/7','11.3','','','']);
 assert.deepEqual(restoredRows.rows[0].valueKinds.slice(3,6),['null','absent','string']);
 assert.deepEqual(restoredRows.columns.map(c=>[c.representation,c.radix]),columns.map(c=>[c.representation,c.radix]));
 assert.equal(restoredRows.rows[0].cells[6].sha256,(await materials.datasetPage(ref,0,{columnOffset:6,columnLimit:1})).rows[0].cells[0].sha256);
 const location=restoredRows.rows[0].cellSources[0][0];
 assert.equal(location.ref.revision,received.revision);
 assert.equal(JSON.parse(original.subarray(location.selector.offset,location.selector.offset+location.selector.length)).text,'9007199254740993');
 const denied={...options,checkSource:async()=>{throw Object.assign(new Error('revoked'),{code:'ACCESS_LOCKED'});}};
 await assert.rejects(exchangeArchive(fixture.workspace,job,prepared,denied).next(),{code:'ACCESS_LOCKED'});
 await removeExchangeAttempt(fixture.workspace,job,attempt);
});
