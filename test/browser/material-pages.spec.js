import os from 'node:os';
import {mkdtemp,rm} from 'node:fs/promises';
import path from 'node:path';
import {test,expect} from '@playwright/test';
import {encryptedFixture} from './encrypted-fixture.js';
import {sampleNotebook} from '../../src/sample.js';
import {ResearchMaterials} from '../../src/research-materials.js';
import {clearVault} from '../../src/encryption.js';
import {startServer} from '../../src/server.js';

test('evidence sources page, search and cross records without losing exact selections or draft fields',async({page})=>{
 test.setTimeout(120000);
 const directory=await mkdtemp(path.join(os.tmpdir(),'observanda-material-picker-')),book=sampleNotebook();
 const {workspace:ws,vault,deviceStore}=await encryptedFixture(directory,book),saved=(await ws.read()).book,owner=saved.entries[0].id,other=saved.entries[1].id,materials=new ResearchMaterials(ws);
 await ws.withLock(async()=>{for(let i=0;i<25;i++)await materials.commit({kind:'collection',recordId:owner,title:'Source '+String(i).padStart(2,'0'),content:{inputs:[]}});await materials.commit({kind:'collection',recordId:other,title:'Shared method inputs',content:{inputs:[]}});});
 const app=await startServer({root:ws.root,deviceStore,port:0,preferencesFile:path.join(directory,'preferences.json')}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 try{
  await page.goto(app.url);await page.evaluate(id=>location.hash='#/records/'+id,owner);
  await page.getByRole('button',{name:'Open evidence & analysis'}).click();
  const dialog=page.locator('#dialog');
  await expect(dialog.locator('.material-list > li')).toHaveCount(20);
  await expect(dialog.locator('[data-dependency-status="checked"]')).toHaveCount(20);
  await dialog.getByRole('button',{name:'Older evidence',exact:true}).click();
  await expect(dialog.locator('.material-list > li')).toHaveCount(5);
  await expect(dialog.locator('[data-dependency-status="checked"]')).toHaveCount(5);
  await dialog.getByText('Analysis, collections & verification',{exact:true}).click();
  await dialog.getByRole('button',{name:'Create collection',exact:true}).click();
  const picker=dialog.locator('#material-picker-inputs');
  await expect(picker.getByRole('checkbox')).toHaveCount(20);
  let lost=false;
  await page.route('**/api/research/materials/selection-change',async route=>{
   if(!lost){lost=true;await route.fetch();await route.abort('failed');}else await route.continue();
  });
  await picker.getByRole('checkbox').first().check();
  await expect(picker).not.toHaveAttribute('aria-busy','true');
  await expect(picker.locator('[data-status]')).toContainText('fetch');
  await expect(picker.getByRole('checkbox').first()).not.toBeChecked();
  await picker.getByRole('checkbox').first().check();
  await expect(picker.locator('[data-selection]')).toContainText('1 selected');
  await dialog.getByRole('button',{name:'Back to evidence',exact:true}).click();
  await expect(page.locator('#leave-dialog')).toBeVisible();
  await page.locator('#leave-dialog').getByRole('button',{name:'Stay here',exact:true}).click();
  await expect(picker.locator('[data-selection]')).toContainText('1 selected');
  await dialog.getByLabel('Title',{exact:true}).fill('Chosen exact sources');
  await picker.getByRole('button',{name:'More sources',exact:true}).click();
  await expect(picker.getByRole('checkbox')).toHaveCount(5);await picker.getByRole('checkbox').first().check();
  await picker.getByLabel('Sources for Exact input revisions').selectOption('all');
  await expect(picker.locator('[data-status]')).not.toHaveText('Loading sources…');
  await picker.getByLabel('Search exact input revisions').fill('Shared method');
  await picker.getByLabel('Search exact input revisions').press('Enter');
  await expect(picker.getByRole('checkbox')).toHaveCount(1);await picker.getByRole('checkbox').check();
  await expect(picker.locator('[data-selection]')).toContainText('3 selected');
  const checkpoint=JSON.parse(await picker.locator('[data-value]').inputValue()),expected=(await materials.choices.page({recordId:owner,selection:checkpoint.selection})).items.map(({kind,id,revision})=>({kind,id,revision}));
  const selected=expected[0],old=await materials.read(selected);
  await ws.withLock(()=>materials.commit({kind:old.kind,id:old.id,recordId:old.recordId,expectedRevision:selected.revision,title:'Changed after selection',content:{inputs:[]}}));
  await picker.getByRole('button',{name:'Refresh sources',exact:true}).click();
  await expect(picker.locator('[data-status]')).not.toHaveText('Loading sources…');
  await expect(dialog.getByLabel('Title',{exact:true})).toHaveValue('Chosen exact sources');
  expect(JSON.parse(await picker.locator('[data-value]').inputValue())).toEqual(checkpoint);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.documentElement.style.fontSize='150%');
  expect(await picker.evaluate(el=>el.scrollWidth<=el.clientWidth+2)).toBe(true);
  await dialog.screenshot({path:test.info().outputPath('source-picker-phone.png')});
  await dialog.getByRole('button',{name:'Save collection',exact:true}).click();
  await expect(dialog.getByRole('heading',{name:'Evidence & analysis',exact:true})).toBeVisible();
  const result=(await materials.list({recordId:owner,query:'Chosen exact sources'})).items[0];
  expect((await materials.referencePage(result)).items.map(({kind,id,revision})=>({kind,id,revision}))).toEqual(expected);
  expect(errors).toEqual([]);
 }finally{await app.close();clearVault(vault);await rm(directory,{recursive:true,force:true});}
});
