
import {test,expect} from '@playwright/test';
import {mkdtemp} from 'node:fs/promises';
import path from 'node:path';
import {Workspace} from '../../src/storage.js';
import {sampleNotebook} from '../../src/sample.js';
import {defaultDashboard} from '../../src/web/dashboard-model.js';
import {saveDashboard,dashboardSnapshot} from '../../src/preferences.js';
import {startServer} from '../../src/server.js';
test('formatted research links and multiple series survive save, reopen and export',async({page})=>{
 const directory=await mkdtemp(path.resolve('.local/ux-review/shared-content-')),root=path.join(directory,'notebook'),book=sampleNotebook(),ws=new Workspace(root);
 await ws.create(book);const preferencesFile=path.join(directory,'preferences.json'),settings=defaultDashboard();settings.enabledModules.push('planning');await saveDashboard(preferencesFile,settings,dashboardSnapshot(defaultDashboard()).etag);const app=await startServer({root,port:0,preferencesFile});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(app.url);
  await page.locator('[data-action="edit-entry"][data-id="'+book.entries[0].id+'"]').first().click();
  const editor=page.getByRole('textbox',{name:'Summary / context',exact:true});
  await editor.fill('Comparing the reference experiment');
  await editor.press('Control+a');await editor.press('Control+b');
  await page.locator('.document-tools [data-rich-command="link"]').first().click();
  const dialog=page.getByRole('dialog',{name:'Link settings'});
  await dialog.getByRole('searchbox').fill(book.entries[1].title);
  await dialog.locator('[data-rich-destination]:visible').click();
  await dialog.getByRole('button',{name:'Apply link',exact:true}).click();
  await expect(editor.locator('a')).toHaveAttribute('href',/observanda:/);
  await expect(editor.locator('strong')).toContainText('Comparing');
  const figure=page.locator('.figure-workbench').first();
  await figure.getByLabel('Horizontal coordinates',{exact:true}).selectOption('number');
  await figure.getByLabel('Plot type',{exact:true}).selectOption('scatter');
  await figure.locator('.figure-import>summary').click();
  await figure.getByLabel('Data to import').fill('Time,Control,Treatment\n0,2,3\n1,4,6\n10,8,12');
  await figure.getByRole('button',{name:'Review data',exact:true}).click();
  await figure.getByRole('button',{name:'Use mapped data',exact:true}).click();
  await expect(figure.locator('svg circle[r="3.5"]')).toHaveCount(6);
  await figure.getByLabel('Uncertainty 2',{exact:true}).fill('0.5');
  await figure.getByRole('button',{name:'Duplicate',exact:true}).click();
  await expect(page.locator('.figure-workbench')).toHaveCount(2);
  await page.getByRole('button',{name:'Save record',exact:true}).click();
  await expect(page.locator('#notice')).toContainText('Changes saved.');
  const saved=(await ws.read()).book.entries[0];
  expect(saved.body.content[0].content[0].marks.map(m=>m.type)).toEqual(expect.arrayContaining(['strong','link']));
  expect(saved.figures).toHaveLength(2);
  expect(saved.figures[0].series[0].points[2].x).toBe(10);
  expect(saved.figures[0].series[0].points[1].error).toBe(.5);
  await editor.press('End');await editor.press('ArrowRight');await editor.press('Space');await editor.pressSequentially('Further observation.');
  await page.getByRole('button',{name:'Save record',exact:true}).click();
  await expect.poll(async()=>JSON.stringify((await ws.read()).book.entries[0].body)).toContain('Further observation.');
  await page.reload();await expect(page.locator('.figure-workbench')).toHaveCount(2);
  await expect(page.getByRole('textbox',{name:'Summary / context',exact:true}).locator('a')).toContainText('Comparing');
  const download=page.waitForEvent('download');
  await page.locator('.figure-workbench').first().getByRole('button',{name:'Download SVG'}).click();
  expect((await download).suggestedFilename()).toMatch(/\.svg$/);
  await page.locator('.figure-workbench').first().evaluate(node=>scrollTo(0,node.getBoundingClientRect().top+scrollY-80));
  await page.screenshot({path:path.join(directory,'figures-desktop.png')});
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(directory,'writing-phone.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Calendar & planning',exact:true}).click();
  await page.getByRole('button',{name:'Tasks',exact:true}).click();
  await page.getByRole('button',{name:'New task',exact:true}).click();
  await page.getByRole('textbox',{name:'Task title',exact:true}).fill('Compare observations');
  const note=page.getByRole('textbox',{name:'Work to do',exact:true});
  await note.fill('Use the same reference experiment');await note.press('Control+a');await note.press('Control+i');
  await page.getByRole('button',{name:'Save task',exact:true}).click();
  await expect(page.locator('#notice')).toContainText('Saved.');
  await page.reload();await expect(page.getByRole('textbox',{name:'Work to do',exact:true}).locator('em')).toContainText('Use the same');
  expect(errors).toEqual([]);
 }finally{await new Promise(r=>app.server.close(r));}
});
