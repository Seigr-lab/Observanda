import {test,expect} from '@playwright/test';
import os from 'node:os';
import {mkdtemp,rm} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {Workspace} from '../../src/storage.js';
import {sampleNotebook} from '../../src/sample.js';
import {workspaceModules} from '../../src/modules/index.js';
import {defaultDashboard} from '../../src/web/dashboard-model.js';
import {saveDashboard,dashboardSnapshot} from '../../src/preferences.js';
import {startServer} from '../../src/server.js';

test('project tools are opt-in, saved explicitly, retained when disabled and highlight only their own scope',async({page})=>{
 test.setTimeout(120000);
 const directory=await mkdtemp(path.join(os.tmpdir(),'observanda-project-tools-')),root=path.join(directory,'workspace'),book=sampleNotebook(),parent=book.projects[0];
 parent.title='Collective';
 const child={...parent,id:randomUUID(),title:'Music studio',parentId:parent.id},other={...parent,id:randomUUID(),title:'Field team'};book.projects.push(child,other);
 book.notebooks[0].title='Inventory';
 const workspace=new Workspace(root);await workspace.create(book);const store=workspaceModules(workspace),item=randomUUID();
 await store.execute({workspaceId:book.id,commandId:randomUUID(),action:'resource.save',payload:{id:item,expectedRevision:null,data:{projectId:child.id,name:'Audio interface',code:'',kind:'equipment',description:'',categoryId:null,schemaRevision:null,fieldSchema:[],values:{},location:'',unit:'',capacity:1,status:'available',links:[]}}});
 const settings=defaultDashboard(),preferencesFile=path.join(directory,'preferences.json');settings.enabledModules.push('resources','planning');
 await saveDashboard(preferencesFile,settings,dashboardSnapshot(defaultDashboard()).etag);
 const app=await startServer({root,port:0,preferencesFile}),main=page.locator('#main'),nav=page.locator('#main-navigation'),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const project=id=>nav.locator('details[data-project-id="'+id+'"]');
 const prefs=async()=>{await nav.getByRole('button',{name:'Preferences',exact:true}).click();await main.getByRole('button',{name:'Modules',exact:true}).click();};
 const controls=()=>main.locator('[data-module-settings-slot="resources"]');
 const choose=async()=>{const toggle=main.locator('[data-module-settings-id="resources"]');if(await toggle.getAttribute('aria-expanded')!=='true')await toggle.click();await controls().getByRole('heading',{name:'Inventory locations'}).waitFor();};
 try{
  await page.goto(app.url);
  await expect(nav.locator('[data-action="open-project"][data-id="'+parent.id+'"]')).toBeVisible();
  await expect(nav.locator('.location-tool-link')).toHaveCount(0);
  await page.evaluate(()=>{document.querySelectorAll('.tree-project').forEach(n=>n.open=true);window.savedTree=document.querySelector('.workspace-tree');});
  await prefs();await choose();
  const checkbox=controls().locator('[data-tool-project="'+child.id+'"]');
  await expect(checkbox).not.toBeChecked();await checkbox.check();
  await expect(nav.locator('.location-tool-link')).toHaveCount(0);
  expect((await workspace.read()).book.projects.find(p=>p.id===child.id).tools??[]).toEqual([]);
  await controls().getByRole('button',{name:'Discard changes',exact:true}).click();await expect(checkbox).not.toBeChecked();
  await checkbox.check();await controls().getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(project(child.id).getByRole('button',{name:'Inventory',exact:true})).toBeVisible();
  await expect(project(other.id).locator('.location-tool-link')).toHaveCount(0);
  await expect(project(parent.id).locator(':scope > .location-tool-link')).toHaveText('Inventory overview');
  expect(await page.evaluate(()=>window.savedTree===document.querySelector('.workspace-tree'))).toBe(true);
  await page.screenshot({path:path.join(directory,'project-selection.png'),fullPage:true});
  await project(child.id).getByRole('button',{name:'Inventory',exact:true}).click();
  await expect(main.getByRole('heading',{name:'Audio interface',exact:true})).toBeVisible();
  await expect(nav.locator('[aria-current="page"]')).toHaveCount(1);
  await expect(nav.locator('[aria-current="page"]')).toHaveText('Inventory');
  await nav.locator('[data-module-nav="resources"]').getByRole('button',{name:'Inventory',exact:true}).click();
  await expect(nav.locator('[aria-current="page"]')).toHaveCount(1);
  await page.reload();await expect(main.getByRole('heading',{name:'Audio interface',exact:true})).toBeVisible();
  await page.evaluate(()=>document.querySelectorAll('.tree-project').forEach(n=>n.open=true));
  await prefs();await choose();await controls().locator('[data-tool-project="'+child.id+'"]').uncheck();
  await controls().getByRole('button',{name:'Save changes',exact:true}).click();await expect(nav.locator('.location-tool-link')).toHaveCount(0);
  expect((await store.read()).entities.find(e=>e.id===item).data.name).toBe('Audio interface');
  await page.goto(new URL('/#/modules/resources/scope/'+child.id+'/resource',app.url).href);
  await expect(main).toContainText('This tool is not enabled for this project.');
  await nav.locator('[data-module-nav="resources"]').getByRole('button',{name:'Inventory',exact:true}).click();
  await expect(main.getByRole('heading',{name:'Audio interface',exact:true})).toBeVisible();
  await page.evaluate(()=>document.querySelectorAll('.tree-project').forEach(n=>n.open=true));
  await nav.locator('[data-action="open-project"][data-id="'+child.id+'"]').click();
  await main.getByRole('button',{name:'Settings',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('checkbox',{name:'Inventory',exact:true}).check();
  await dialog.getByRole('button',{name:'Save project',exact:true}).click();
  await main.getByRole('button',{name:/^Inventory/}).click();
  await expect(main.getByRole('heading',{name:'Audio interface',exact:true})).toBeVisible();
  await main.getByRole('button',{name:'New item',exact:true}).click();
  await expect(main.getByLabel('Owned by')).toHaveValue('');
  await expect(main.getByLabel('Held at',{exact:true})).toHaveValue(child.id);
  await expect(main.getByLabel('Held at',{exact:true}).locator('option[value="'+other.id+'"]')).toHaveCount(0);
  await main.getByRole('button',{name:'Discard edits',exact:true}).click();
  await prefs();
  await main.getByRole('switch',{name:'Enable Inventory',exact:true}).uncheck();
  await expect(nav.locator('[data-module-id="resources"]')).toHaveCount(0);
  await main.getByRole('switch',{name:'Enable Inventory',exact:true}).check();
  await expect(project(child.id).getByRole('button',{name:'Inventory',exact:true})).toBeVisible();
  await choose();if(await page.locator('#notice').isVisible())await page.locator('#notice').getByRole('button',{name:'Dismiss'}).click();await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(directory,'project-selection-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  expect((await workspace.read()).book.notebooks[0].title).toBe('Inventory');
  expect(errors).toEqual([]);
 }finally{await app.close();await rm(directory,{recursive:true,force:true});}
});
