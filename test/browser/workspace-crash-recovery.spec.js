import {test,expect} from '@playwright/test';
import {setRecordTitle} from './record-editing-helper.js';
import {mkdtemp,rm,readFile,access} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {sampleNotebook} from '../../src/sample.js';
import {upgradeNotebook} from '../../src/model.js';
import {encryptedFixture} from './encrypted-fixture.js';
import {interruptWorkspace} from '../fixtures/interrupt-workspace.js';
import {startServer} from '../../src/server.js';
import {clearVault} from '../../src/encryption.js';
import {Workspace} from '../../src/storage.js';
import {ResearchMaterials,EVIDENCE_CHUNK} from '../../src/research-materials.js';
import {copyPlan,copyWorkspace,readPreference} from '../../src/locations.js';
import {CATALOGUE_ARCHIVE} from '../../src/postgres.js';
import {CATALOGUE_ACTIVATION} from '../../src/postgres-activation.js';
import {preferences} from './preferences-helper.js';

test('the app reopens an interrupted restore, backs up a killed upload and resumes the original',async({page})=>{
 test.setTimeout(90000);page.setDefaultTimeout(15000);
 const directory=await mkdtemp(path.join(os.tmpdir(),'observanda-crash-ui-')),book=upgradeNotebook(sampleNotebook());
 const f=await encryptedFixture(directory,book),bytes=Buffer.alloc(EVIDENCE_CHUNK+8192,0x5a),materials=new ResearchMaterials(f.workspace);
 let app;
 try{
  const session=await materials.startImport({recordId:book.entries[0].id,name:'returned-capture.bin',size:bytes.length});
  await materials.appendImport(session.id,0,[bytes.subarray(0,EVIDENCE_CHUNK)]);
  const backup=await copyWorkspace(await copyPlan(f.workspace.root,path.join(directory,'restore')),{vault:f.vault});
  await interruptWorkspace(backup,f.vault,'retire');
  await access(path.join(backup,CATALOGUE_ARCHIVE));
  const preferencesFile=path.join(directory,'preferences.json');
  const options={root:backup,port:0,headless:true,deviceStore:f.deviceStore,preferencesFile};
  app=await startServer(options);const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(app.url);await expect(page.locator('.workspace-name')).toHaveText(book.title);
  await expect(access(path.join(backup,CATALOGUE_ARCHIVE))).rejects.toMatchObject({code:'ENOENT'});
  await expect(access(path.join(backup,CATALOGUE_ACTIVATION))).rejects.toMatchObject({code:'ENOENT'});
  await app.close();app=null;
  await interruptWorkspace(backup,f.vault,'upload-stream',{upload:{id:session.id,index:1}});
  app=await startServer(options);await page.goto(app.url);await expect(page.locator('.workspace-name')).toHaveText(book.title);
  const destination=path.join(directory,'continued'),dialog=page.locator('#dialog');
  await preferences(page,'Storage & access');await page.getByRole('button',{name:'Copy workspace to another folder',exact:true}).click();
  await dialog.getByLabel('Workspace folder',{exact:true}).fill(destination);
  await dialog.getByRole('button',{name:'Copy and use this folder',exact:true}).click();await expect(dialog).not.toBeVisible();
  expect(await readPreference(preferencesFile)).toBe(destination);
  await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible();
  await page.evaluate(id=>location.hash='#/records/'+id,book.entries[0].id);
  await page.getByRole('button',{name:'Open evidence & analysis',exact:true}).click();
  await dialog.getByRole('button',{name:'Resume upload',exact:true}).click();
  await dialog.getByLabel('Select the same original file',{exact:true}).setInputFiles({name:session.name,mimeType:'application/octet-stream',buffer:bytes});
  const uploads=[];page.on('request',request=>{if(request.url().includes('/api/research/materials/chunk/'))uploads.push(new URL(request.url()).pathname);});
  await dialog.getByRole('button',{name:'Resume import',exact:true}).click();
  await expect(dialog.getByRole('heading',{name:'Evidence & analysis',exact:true})).toBeVisible();
  const downloadEvent=page.waitForEvent('download');await dialog.getByRole('link',{name:'Download '+session.name,exact:true}).click();
  expect(await readFile(await (await downloadEvent).path())).toEqual(bytes);
  expect(uploads).toEqual(['/api/research/materials/chunk/'+session.id+'/1']);
  const restored=new ResearchMaterials(new Workspace(destination,f.vault));expect((await restored.heads()).filter(h=>h.kind==='artifact')).toHaveLength(1);
  expect(materials.uploads.count(await materials.importState(session.id))).toBe(1);
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await setRecordTitle(page,'Work continues after recovery');await page.reload();await expect(page.locator('.record-editing h1')).toHaveText('Work continues after recovery');
  expect((await f.workspace.read()).book.entries[0].title).toBe(book.entries[0].title);expect(errors).toEqual([]);
 }finally{await app?.close();clearVault(f.vault);await rm(directory,{recursive:true,force:true,maxRetries:10,retryDelay:100});}
});
