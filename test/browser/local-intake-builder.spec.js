import {test,expect} from '@playwright/test';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {intakeFixture} from '../fixtures/local-intake.js';
import {retainDatasetOriginal} from '../fixtures/dataset-original.js';
import {startServer} from '../../src/server.js';
import {defaultColumn} from '../../src/web/dataset-schema.js';
import {executeMaterialRequest} from '../../src/material-requests.js';
import {validateIntake} from '../../src/intake/contract.js';

test('select a named target, build and download a manifest, stage ten files, review evidence and reuse the saved interpretation through the record',async({page})=>{
 test.setTimeout(220000);page.setDefaultTimeout(18000);
 let cleanup;const f=await intakeFixture({after:fn=>{cleanup=fn;}}),materials=f.service.materials;
 const selected=f.book.entries.find(entry=>entry.id!==f.record.id),source=path.join(f.directory,'device-export');await mkdir(source);
 const contents=['run,signal\n1,5\n','signal,run\n4,2\n','run\n3\n','run,signal\n4,8\n',...Array.from({length:6},(_,i)=>'run,signal\n'+(i+5)+',3\n')];
 for(const [i,bytes] of contents.entries())await writeFile(path.join(source,'device-'+String(i+1).padStart(2,'0')+'.csv'),bytes);
 const bytes=Buffer.from(contents[0]),original=await retainDatasetOriginal(materials,f.record.id,'template.csv',bytes.length,[bytes]);
 const template=await materials.dataset({recordId:f.record.id,title:'Device readings',artifact:original,
  columns:[defaultColumn({label:'Run'}),{...defaultColumn({label:'Signal'}),representation:'radix',radix:6}]});
 const command={id:randomUUID(),recordId:f.record.id,expectedRevision:null,title:'Logger – exact base six',template,rules:[]};
 const request=(material,data)=>executeMaterialRequest(f.ws,{material},data);
 const {review}=await request('dataset-profile-revision',{command,offset:0,limit:16});await request('dataset-profile-save',{command,review});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const app=await startServer({root:f.ws.root,deviceStore:f.deviceStore,headless:true,preferencesFile:path.join(f.directory,'ui-preferences.json')});
 try{
  await page.goto(app.url);await page.goto(app.origin+'/#/records/'+f.record.id);
  await page.getByRole('button',{name:'Evidence and results',exact:true}).click();
  await page.getByRole('button',{name:'Open evidence & analysis',exact:true}).click();
  const dialog=page.locator('#dialog');
  await dialog.getByRole('button',{name:'Intake & readiness',exact:true}).click();
  await dialog.getByRole('button',{name:'Build a package from files'}).click();
  await dialog.getByRole('button',{name:'Choose destination record'}).click();
  const targetPicker=dialog.locator('[data-target-picker]');
  await targetPicker.getByRole('button',{name:new RegExp(selected.title.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))}).click();
  await expect(dialog.locator('[data-target]')).toContainText(selected.title);
  await dialog.getByLabel('Proposal folder',{exact:true}).fill(source);
  await dialog.getByRole('button',{name:'Browse files',exact:true}).click();
  await expect(dialog.getByRole('checkbox',{name:'device-10.csv'})).toBeVisible();
  await dialog.getByRole('button',{name:'Select folder and subfolders'}).click();
  await expect(dialog.locator('[data-count]')).toContainText('10');
  await dialog.getByLabel('Package title').fill('Reviewed logger exports');
  await dialog.getByLabel('Method or procedure').fill('Read logger channels');
  await dialog.getByRole('button',{name:'Choose interpretation profile'}).click();
  await dialog.getByRole('button',{name:'Logger – exact base six',exact:true}).click();
  await dialog.locator('details').filter({has:page.locator('[data-field="adapterName"]')}).locator('summary').click();
  await dialog.getByLabel('Adapter name').fill('Field logger adapter');
  await dialog.getByRole('button',{name:'Save reusable adapter',exact:true}).click();
  await expect(dialog.locator('[data-build-status]')).toHaveText('Adapter saved.',{timeout:35000});
  await dialog.getByRole('button',{name:'Keep recovery copy and close'}).click();await expect(dialog).toBeHidden();
  await page.getByRole('button',{name:'Open evidence & analysis',exact:true}).click();
  await dialog.locator('[data-action="material-recovery-open"]').click();
  await expect(dialog.getByLabel('Package title')).toHaveValue('Reviewed logger exports');
  await expect(dialog.locator('[data-target]')).toContainText(selected.title);
  await expect(dialog.locator('[data-count]')).toContainText('10');
  await expect(dialog.locator('[data-settings]')).toContainText('Field logger adapter');
  await dialog.getByRole('button',{name:'Review package'}).click();
  await expect(dialog.locator('[data-preview]')).toContainText(selected.title);
  const download=page.waitForEvent('download');await dialog.getByRole('button',{name:'Download manifest'}).click();
  const saved=await download;
  expect(saved.suggestedFilename()).toBe('intake.observanda.json');
  const manifest=validateIntake(JSON.parse(await readFile(await saved.path(),'utf8')));expect(manifest.recordId).toBe(selected.id);
  expect(manifest.files).toHaveLength(10);expect(manifest.analyses[0].inputs).toHaveLength(12);
  await dialog.getByRole('button',{name:'Stage privately'}).click();
  await dialog.getByRole('button',{name:'Apply reviewed proposal'}).click({timeout:80000});
  await dialog.getByRole('button',{name:'Review interpretation of retained files'}).click({timeout:80000});
  await dialog.getByRole('button',{name:'Check selected files'}).click();
  await expect(dialog.locator('[data-profile-panel] [data-status]').last()).toHaveText('10 files checked',{timeout:80000});
  const result=n=>dialog.locator('[data-report] details').filter({has:page.locator('summary').filter({hasText:'device-'+n+'.csv'})});
  await result('02').locator('summary').click();await expect(result('02').getByRole('cell',{name:'Reordered column'}).first()).toBeVisible();
  await result('03').locator('summary').click();await expect(result('03').getByRole('cell',{name:'Required column missing'})).toBeVisible();
  await expect(result('03').getByRole('row').filter({hasText:'Required column missing'}).getByRole('cell',{name:'Line 1',exact:true})).toBeVisible();
  await result('04').locator('summary').click();await expect(result('04').getByText('8',{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'Retain eligible datasets'}).click();
  await expect(dialog.locator('[data-profile-panel] [data-status]').last()).toHaveText('8 dataset jobs submitted',{timeout:80000});
  await result('02').getByRole('button',{name:'Open dataset job'}).click();
  await expect(dialog.getByRole('heading',{name:'device-02.csv',exact:true})).toBeVisible({timeout:80000});
  expect(errors).toEqual([]);
 }finally{await app.close();await cleanup();}
});
