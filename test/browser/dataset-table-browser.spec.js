import {test,expect} from '@playwright/test';
import {realpath,mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {encryptedFixture} from './encrypted-fixture.js';
import {sampleNotebook} from '../../src/sample.js';
import {clearVault} from '../../src/encryption.js';
import {ResearchMaterials} from '../../src/research-materials.js';
import {defaultColumn} from '../../src/web/dataset-schema.js';
import {startServer} from '../../src/server.js';
import {openEvidence} from './record-editor-helper.js';

test('navigate retained table values, save a filtered view and return from an exact cell inspection with keyboard selection',async({page,context})=>{
 test.setTimeout(180000);page.setDefaultTimeout(15000);
 const parent=await realpath(os.tmpdir()),directory=await mkdtemp(path.join(parent,'observanda-table-view-')),book=sampleNotebook(),recordId=book.entries[0].id;
 let fixture,app;const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 try{
  fixture=await encryptedFixture(directory,book);const materials=new ResearchMaterials(fixture.workspace);
  const labels=Array.from({length:20},(_,i)=>i===19?'Reference count':'Channel '+(i+1)),base=9007199254740992n;
  const bytes=Buffer.from([labels.join(','),...Array.from({length:70},(_,r)=>labels.map((_,c)=>c===19?String(base+BigInt(r)):String(100*r+c)).join(','))].join('\n'));
  const upload=await materials.startImport({recordId,name:'measurements.csv',size:bytes.length});await materials.appendImport(upload.id,0,[bytes]);
  const artifact=await materials.finishImport(upload.id);
  const source=await materials.dataset({recordId,artifact,title:'Survey readings',columns:labels.map(label=>({...defaultColumn({label}),representation:'integer'})),exclusions:{[artifact.id+':71']:'Instrument offline'}});
  const figure=await materials.plot({recordId,title:'Retained count figure',dataset:source,mapping:{x:19,xKind:'category',values:[{column:0,error:null}],group:null,operation:'raw',order:'source',kind:'line',mode:'replace',decimal:'.'}});
  const figureBefore=await materials.read(figure.ref);
  app=await startServer({root:fixture.workspace.root,deviceStore:fixture.deviceStore,headless:true});
  await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:app.origin});
  await page.goto(app.url);await page.goto(app.origin+'/#/records/'+recordId);
  await page.getByRole('button',{name:'Evidence and results',exact:true}).click();
  await openEvidence(page);
  const dialog=page.locator('#dialog');
  await dialog.locator('.material-list li').filter({has:page.getByText('Survey readings',{exact:true})}).getByRole('button',{name:'Inspect',exact:true}).click();
  const tools=dialog.getByRole('region',{name:'Table view'}),grid=dialog.getByRole('grid');
  await expect(grid).toBeVisible();
  await tools.getByLabel('Go to result row').fill('66');await tools.getByRole('button',{name:'Go',exact:true}).click();
  await expect(grid.locator('tbody th').first()).toHaveText('66'+artifact.id+':67');
  await tools.locator('summary').filter({hasText:/^Columns$/}).click();
  await tools.getByLabel('Find a column').fill('reference count');await tools.getByLabel('Find a column').press('Enter');
  const match=tools.locator('[data-column-results] .inline-actions').filter({hasText:'20. Reference count'});
  await match.getByRole('button',{name:'Pin',exact:true}).click();
  await expect(grid.locator('thead th').nth(1)).toContainText('Reference count');
  await match.getByRole('button',{name:'Use for filtering or sorting'}).click();
  await tools.getByRole('combobox',{name:'Condition',exact:true}).selectOption('greater');
  await tools.getByLabel('Value',{exact:true}).fill(String(base+66n));await tools.getByRole('button',{name:'Add condition'}).click();
  await tools.getByRole('combobox',{name:'Sort by selected column',exact:true}).selectOption('descending');
  await tools.getByRole('button',{name:'Apply view'}).click();
  const first=grid.locator('[data-table-row="0"][data-table-column="0"]');
  await expect(first).toHaveText(String(base+69n));
  await expect(grid.locator('tbody tr')).toHaveCount(3);
  await expect(grid.locator('tbody tr').first()).toContainText('Instrument offline');
  await first.focus();await first.press('Shift+ArrowDown');await page.keyboard.press('Control+c');
  await expect.poll(()=>page.evaluate(()=>navigator.clipboard.readText())).toBe(String(base+69n)+'\r\n'+String(base+68n));
  const second=grid.locator('[data-table-row="1"][data-table-column="0"]');
  await expect(second).toBeFocused();
  const scroll=await grid.evaluate(table=>{
   const region=table.closest('.material-table'),form=table.closest('form');
   region.scrollLeft=95;form.scrollTop=50;
   return [region.scrollLeft,form.scrollTop];
  });
  expect(scroll[0]).toBeGreaterThan(0);
  await second.press('Enter');
  await expect(dialog.locator('[data-measurement-inspection]')).toContainText(artifact.id+':70');
  await dialog.getByRole('button',{name:'Back to source',exact:true}).click();
  await expect(second).toBeFocused();await expect(second).toHaveText(String(base+68n));
  expect(await grid.evaluate(table=>[table.closest('.material-table').scrollLeft,table.closest('form').scrollTop])).toEqual(scroll);
  await expect(grid.locator('td[aria-selected=true]')).toHaveCount(2);
  await tools.locator('summary').filter({hasText:/^Saved views$/}).click();
  await tools.getByLabel('View name').fill('High counts');await tools.getByRole('button',{name:'Save view',exact:true}).click();
  await expect(tools.getByText('High counts',{exact:true})).toBeVisible();
  await tools.getByRole('button',{name:'Clear filters and sorting'}).click();await expect(grid.locator('tbody tr')).toHaveCount(32);
  await tools.getByRole('button',{name:'Open view',exact:true}).click();await expect(first).toHaveText(String(base+69n));
  await dialog.getByRole('button',{name:'Create reproducible figure',exact:true}).click();
  const pager=dialog.locator('[data-column-pager]');
  await pager.getByLabel('Find a column').fill('reference count');await pager.getByLabel('Find a column').press('Enter');
  await pager.getByRole('button',{name:'20. Reference count'}).click();
  await expect(dialog.getByRole('checkbox',{name:/Reference count/})).toBeVisible();
  expect((await materials.current(source.id)).revision).toBe(source.revision);
  const figureHead=await materials.current(figure.ref.id);
  expect(figureHead.revision).toBe(figure.ref.revision);
  expect((await materials.read(figureHead)).content).toEqual(figureBefore.content);
  expect(errors).toEqual([]);
 }finally{
  await app?.close();if(fixture)await clearVault(fixture.vault);expect(path.dirname(directory)).toBe(parent);
  await rm(directory,{recursive:true,force:true,maxRetries:8,retryDelay:100});
 }
});
