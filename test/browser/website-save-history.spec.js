import {test,expect} from '@playwright/test';
import {createHash,randomUUID} from 'node:crypto';
import {mkdtemp,mkdir,readFile,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createNotebook} from '../../src/model.js';
import {clearVault} from '../../src/encryption.js';
import {WebsiteFileStore} from '../../src/website-file-store.js';
import {encryptedFixture} from './encrypted-fixture.js';
import {testServer} from '../device-fixture.js';

test('save, undo and redo writing, styling, order and owned media; withdraw a source before replay',async({page,browser})=>{
 test.setTimeout(120000);
 const root=await mkdtemp(path.join(os.tmpdir(),'observanda-edit-history-')),folder=path.join(root,'Edition');
 let fixture,app,reader;const database=process.env.OBSERVANDA_DATABASE_URL;
 try{
  await mkdir(folder);fixture=await encryptedFixture(root,createNotebook('Methods'));
  const store=new WebsiteFileStore(fixture.workspace),id=randomUUID(),sourceId=createHash('sha256').update(randomUUID()).digest('hex');
  const created=await store.create({id,name:'Method guide',html:'<html><head><title>Methods</title><link rel="stylesheet" href="style.css"></head><body><main><h1>Methods</h1><p>Exposure</p><p>Temperature</p><section id="training"><h2>Specimen card</h2><p>Field training</p></section></main></body></html>',css:''});
  const bytes=await readFile(new URL('../../src/preview-assets/image.png',import.meta.url));
  const asset='assets/'+createHash('sha256').update(bytes).digest('hex')+'.png';
  const grant=await store.beginSourceUpdate({sourceId});
  await store.putSource({sourceId,title:'Field note',html:'<section data-observanda-part="body"><p>Withdrawable observations</p><a href="https://example.org/field">Field link</a><img src="'+asset+'" alt="Field evidence"></section>',assets:[{path:asset,bytes,contentType:'image/png'}]},{token:grant});
  await store.insertSource(id,{sourceId,expectedRevision:created.site.revision});
  process.env.OBSERVANDA_DATABASE_URL='postgresql://unavailable:unavailable@127.0.0.1:1/unavailable';
  app=await testServer({root:fixture.workspace.root,deviceStore:fixture.deviceStore,preferencesFile:path.join(root,'preferences.json'),port:0});
  await page.goto(app.origin+'/?view=website#'+app.launchToken);
  const canvas=page.frameLocator('#website-files-canvas'),text=canvas.locator('main > p').filter({hasText:'Exposure'});
  const first=canvas.locator('main > p').first(),photo=canvas.locator('.site-gallery img');
  const command=name=>page.getByRole('button',{name,exact:true});
  async function save(){await command('Save website').click();await expect(page.locator('[data-website-files-status]')).toHaveText('Website saved.');}
  await text.click();await page.keyboard.press('End');await page.keyboard.insertText(' series');
  await expect(text).toHaveText('Exposure series');
  const inspector=page.locator('[data-website-visual-inspector]');
  await inspector.locator('[data-visual-property="letter-spacing"]').fill('3');
  await inspector.getByRole('button',{name:'Apply styles',exact:true}).click();
  await expect(text).toHaveCSS('letter-spacing','3px');
  await page.locator('[data-action="website-files-move-down"]:enabled').click();
  await expect(first).toHaveText('Temperature');
  await command('Image gallery').click();await page.locator('[data-gallery-files]').setInputFiles('src/preview-assets/image.png');
  await expect(page.locator('[data-gallery-field=alt]')).toBeVisible();await save();
  await page.locator('[data-action=website-files-gallery-close]').click();
  await expect.poll(()=>photo.evaluate(el=>el.naturalWidth)).toBeGreaterThan(0);
  await text.click();await page.keyboard.press('ControlOrMeta+z');await expect(photo).toHaveCount(0);
  await save();await expect(command('Redo')).toBeEnabled();
  await command('Undo').click();await expect(first).toHaveText('Exposure series');
  await command('Undo').click();await expect(text).not.toHaveCSS('letter-spacing','3px');
  await command('Undo').click();await expect(text).toHaveText('Exposure');
  await command('Redo').click();await expect(text).toHaveText('Exposure series');
  await command('Redo').click();await expect(text).toHaveCSS('letter-spacing','3px');
  await command('Redo').click();await expect(first).toHaveText('Temperature');
  await command('Redo').click();await expect.poll(()=>photo.evaluate(el=>el.naturalWidth)).toBeGreaterThan(0);
  await save();await page.reload();await expect(first).toHaveText('Temperature');
  await expect(text).toHaveCSS('letter-spacing','3px');await expect.poll(()=>photo.evaluate(el=>el.naturalWidth)).toBeGreaterThan(0);
  await text.click();await page.keyboard.press('End');await page.keyboard.insertText(' revised');await save();
  const library=page.locator('[data-website-components]');
  await command('Reusable library').click();await canvas.locator('#training').click({position:{x:2,y:2}});
  await library.getByLabel('Component name',{exact:true}).fill('Training notes');await library.getByRole('button',{name:'Create from selected block'}).click();
  await expect(library.getByText('Placements 1 · Pages 1')).toBeVisible();
  const theme=page.getByRole('dialog',{name:'Themes'});
  await command('Themes').click();await theme.getByLabel('Theme name').fill('Methods reading');
  await theme.getByRole('combobox',{name:'Apply to',exact:true}).selectOption('page');await theme.getByRole('button',{name:'Save theme'}).click();
  await expect(theme).not.toBeVisible();await command('Website menu').click();
  const menu=page.getByRole('region',{name:'Website menu',exact:true});
  await menu.getByRole('button',{name:'New menu',exact:true}).click();await menu.getByLabel('Menu name',{exact:true}).fill('References');
  await menu.getByLabel('Location on each page').selectOption('footer');await menu.getByRole('button',{name:'Add menu item'}).click();
  await menu.getByLabel('Menu label',{exact:true}).fill('Method reference');await menu.getByLabel('Link',{exact:true}).fill('index.html');
  await menu.getByRole('button',{name:'Save menu'}).click();await expect(menu.getByRole('button',{name:'Save menu'})).toBeDisabled();
  await menu.getByRole('button',{name:'Return to editing'}).click();
  await command('Undo').click();await expect(text).toHaveText('Exposure series');
  await expect(canvas.locator('[data-website-instance]')).toHaveCount(1);await expect(canvas.locator('[data-website-page-theme]')).toHaveCount(1);
  await expect(canvas.getByRole('link',{name:'Method reference',exact:true})).toHaveCount(1);
  await command('Redo').click();await expect(text).toHaveText('Exposure series revised');
  await text.click();await page.keyboard.press('End');await page.keyboard.insertText(' pending');
  const token=await store.beginSourceUpdate({sourceId});
  await command('Undo').click();await expect(page.locator('#website-files-canvas')).toHaveCount(0);
  await store.putSource({sourceId,title:'Withdrawn',visible:false},{token});
  await expect(text).toHaveText('Exposure series revised pending',{timeout:15000});await expect(command('Undo')).toBeDisabled();await save();
  await expect(canvas.getByText('Withdrawable observations')).toHaveCount(0);await expect(canvas.getByRole('link',{name:'Field link'})).toHaveCount(0);
  const opened=await store.open(id);await expect(store.file(id,asset,{revision:opened.site.revision})).rejects.toMatchObject({code:'NOT_FOUND'});
  await command('Publish to folder').click();await page.getByLabel('Destination folder',{exact:true}).fill(folder);
  await command('Review file changes').click();await page.locator('[data-website-file-folder-confirm]').check();await command('Write reviewed files').click();
  await expect(page.getByText('Edition written and verified.',{exact:true})).toBeVisible();
  reader=await browser.newPage();await reader.goto(pathToFileURL(path.join(folder,'index.html')).href);
  await expect(reader.locator('main > p').first()).toHaveText('Temperature');await expect(reader.getByText('Exposure series revised pending')).toHaveCSS('letter-spacing','3px');
  await expect.poll(()=>reader.locator('.site-gallery img').evaluate(el=>el.naturalWidth)).toBeGreaterThan(0);
  expect(await readFile(path.join(folder,'index.html'),'utf8')).not.toMatch(/Withdrawable observations|https:\/\/example\.org\/field/);
 }finally{
  if(database===undefined)delete process.env.OBSERVANDA_DATABASE_URL;else process.env.OBSERVANDA_DATABASE_URL=database;
  await reader?.close();try{await app?.close();if(fixture)await clearVault(fixture.vault);}finally{await rm(root,{recursive:true,force:true,maxRetries:12,retryDelay:100});}
 }
});
