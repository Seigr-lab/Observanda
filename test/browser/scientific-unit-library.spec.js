import {test,expect} from '@playwright/test';
import {mkdtemp,realpath,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {encryptedFixture} from './encrypted-fixture.js';
import {sampleNotebook} from '../../src/sample.js';
import {ResearchMaterials} from '../../src/research-materials.js';
import {defaultColumn} from '../../src/web/dataset-schema.js';
import {startServer} from '../../src/server.js';
import {clearVault} from '../../src/encryption.js';
import {openEvidence} from './record-editor-helper.js';

test('choose standard temperature points and intervals, preview an exact conversion, then save and reuse an authored unit from the schema editor',async({page})=>{
 test.setTimeout(150000);page.setDefaultTimeout(15000);
 const parent=await realpath(os.tmpdir()),directory=await mkdtemp(path.join(parent,'observanda-unit-picker-')),book=sampleNotebook(),recordId=book.entries[0].id;
 const f=await encryptedFixture(directory,book),materials=new ResearchMaterials(f.workspace);
 let app;const errors=[];page.on('pageerror',error=>errors.push(error.message));
 try{
  const bytes=Buffer.from('Reading\n20\n'),upload=await materials.startImport({recordId,name:'temperature.csv',size:bytes.length});
  await materials.appendImport(upload.id,0,[bytes]);const artifact=await materials.finishImport(upload.id);
  const original=await materials.dataset({recordId,title:'Thermal observation',artifact,columns:[{...defaultColumn({label:'Reading'}),representation:'decimal'}]});
  app=await startServer({root:f.workspace.root,deviceStore:f.deviceStore,preferencesFile:path.join(directory,'preferences.json'),headless:true});
  await page.goto(app.url);await page.goto(app.origin+'/#/records/'+recordId);
  await page.getByRole('button',{name:'Evidence and results',exact:true}).click();await openEvidence(page);
  const dialog=page.locator('#dialog');
  await dialog.locator('.material-list li').filter({hasText:'Thermal observation'}).getByRole('button',{name:'Inspect',exact:true}).click();
  await dialog.getByRole('button',{name:'Edit schema & exclusions'}).click();
  const column=dialog.locator('[data-material-column="0"]'),unit=column.locator('[data-unit-path="quantity.unitDefinition"]');
  await column.locator('summary').filter({hasText:/^Quantity provenance$/}).click();
  const choose=()=>unit.locator('summary').filter({hasText:/^Choose a unit definition$/}).click();
  const select=choice=>unit.getByLabel('Standard units, edition 1').selectOption(choice);
  const apply=()=>unit.getByRole('button',{name:'Apply this unit',exact:true}).click();
  await choose();await select('celsius');await apply();
  await expect(column.getByLabel('Unit',{exact:true})).toHaveValue('°C');
  await choose();await select('kelvin');await unit.locator('summary').filter({hasText:/Preview a conversion/}).click();
  await unit.locator('[data-unit-trial-value]').fill('20');await unit.getByRole('button',{name:'Convert value'}).click();
  await expect(unit.locator('output')).toHaveText('Exact result: 5863/20 K');
  await select('kelvin-interval');await expect(unit.locator('[data-unit-compatibility]')).toContainText('changes the quantity kind');await apply();
  await choose();await select('celsius-interval');await unit.locator('summary').filter({hasText:/Preview a conversion/}).click();
  await unit.locator('[data-unit-trial-value]').fill('20');await unit.getByRole('button',{name:'Convert value'}).click();
  await expect(unit.locator('output')).toHaveText('Exact result: 20 °C');
  await unit.locator('[data-unit-kind]').selectOption('absolute');
  for(const [key,spelling] of [['scale','10.3'],['offset','2.1']]){
   const scalar=unit.locator('[data-unit-scalar="'+key+'"]');
   await scalar.locator('[data-unit-representation]').selectOption('radix-fraction');
   await scalar.locator('[data-unit-radix]').fill('6');await scalar.locator('[data-unit-spelling]').fill(spelling);
  }
  await expect(unit.locator('[data-unit-edition]')).toBeHidden();
  await unit.locator('summary').filter({hasText:/Save or revise a lab unit/}).click();
  await unit.getByLabel('Unit name',{exact:true}).fill('Probe scale');
  await unit.getByLabel('Quantity name',{exact:true}).fill('Sensor temperature');
  await unit.locator('[data-library-symbol]').fill('Tlab');await unit.getByLabel('Aliases, one per line').fill('Probe reading');
  await unit.getByRole('button',{name:'Review definition'}).click();await unit.getByRole('button',{name:'Save this definition'}).click();
  await expect(column.getByLabel('Unit',{exact:true})).toHaveValue('Tlab');
  await choose();await unit.getByLabel('Name, symbol, quantity or alias').fill('probe reading');
  await unit.getByRole('button',{name:'Find lab units'}).click();
  await unit.getByRole('button',{name:'Probe scale · Tlab · Sensor temperature'}).click();
  await unit.getByRole('button',{name:'Favorite this quantity'}).click();
  await unit.getByRole('button',{name:'Revise this unit'}).click();
  const edition=page.getByRole('dialog',{name:'Revise this unit'});
  await edition.getByLabel('Unit name',{exact:true}).fill('Renamed probe scale');
  await edition.getByRole('button',{name:'Review definition'}).click();
  await edition.getByRole('button',{name:'Save this definition'}).click();
  await expect(edition).toHaveCount(0);
  await unit.locator('summary').filter({hasText:'Favorite quantities on this device'}).click();
  const favorite=unit.locator('[data-library-favorite-list] li').filter({hasText:'Probe scale'});
  await expect(favorite).toContainText('Sensor temperature');
  await favorite.getByRole('button',{name:'Apply this unit'}).click();
  await expect(unit.locator('[data-unit-scalar="scale"] [data-unit-spelling]')).toHaveValue('10.3');
  await expect(unit.locator('[data-unit-scalar="offset"] [data-unit-spelling]')).toHaveValue('2.1');
  await expect(unit.locator('[data-unit-edition]')).toContainText('Lab definition revision');
  const calibration=column.locator('[data-calibration-block]');
  await expect(calibration.getByRole('status',{name:'Calibration reference'})).toHaveText('No calibration selected.');
  await calibration.getByRole('button',{name:'Choose retained revision'}).click();
  const picker=calibration.locator('[data-choices] select'),certificate=picker.locator('option').filter({hasText:'temperature.csv'});
  await expect(certificate).toHaveCount(1);await picker.selectOption({label:await certificate.textContent()});
  await calibration.locator('[data-use]').click();await expect(calibration.getByRole('status',{name:'Calibration reference'})).toHaveText('Calibration validity is unknown.');
  await calibration.locator('summary').filter({hasText:'Record certificate validity'}).click();
  await calibration.getByLabel('Certificate name').fill('Temperature certificate');
  await calibration.getByLabel('First valid date').fill('2025-01-01');await calibration.getByLabel('Certificate expiry').selectOption('dated');
  await calibration.getByLabel('Last valid date, inclusive').fill('2025-12-31');
  await calibration.getByRole('button',{name:'Review certificate',exact:true}).click();
  await calibration.getByRole('button',{name:'Save certificate revision'}).click();
  await expect(calibration.getByRole('status',{name:'Calibration reference'})).toHaveText('Choose the observation date to assess calibration.');
  await calibration.getByLabel('Observation date').fill('2026-01-01');
  await expect(calibration.getByRole('status',{name:'Calibration reference'})).toHaveText('Calibration had expired on 2026-01-01.');
  await calibration.getByLabel('Calibration policy').selectOption('require-valid');
  await dialog.getByRole('button',{name:'Save dataset revision'}).click();
  await expect(dialog.getByRole('button',{name:'Save dataset revision'})).toBeVisible();
  await calibration.getByLabel('Observation date').fill('2025-12-31');
  await expect(calibration.getByRole('status',{name:'Calibration reference'})).toHaveText('Calibration covered 2025-12-31.');
  await dialog.getByRole('button',{name:'Save dataset revision'}).click();
  await expect(dialog.getByRole('button',{name:'Edit schema & exclusions'})).toBeVisible({timeout:30000});
  const current=await materials.current(original.id),columnAfter=(await materials.schemaPage(current,{offset:0,limit:1})).items[0];
  expect(columnAfter.unit).toBe('Tlab');expect(columnAfter.quantity.unitDefinition.kind).toBe('absolute');
  expect(columnAfter.quantity.unitDefinition.scale.radix).toBe(6);expect(columnAfter.quantity.unitDefinition.offset.spelling).toBe('2.1');
  expect(columnAfter.quantity.calibrationReview.on).toBe('2025-12-31');
  expect(columnAfter.quantity.calibrationReview.policy).toBe('require-valid');
  expect((await materials.read(columnAfter.quantity.calibration)).title).toBe('Temperature certificate');
  const library=await materials.read(columnAfter.quantity.unitSource);
  expect(library.title).toBe('Probe scale');expect(library.content.unit.aliases).toEqual(['Probe reading']);
  expect((await materials.schemaPage(original,{offset:0,limit:1})).items[0].quantity).toBeUndefined();
  expect(errors).toEqual([]);
 }finally{await app?.close();await clearVault(f.vault);expect(path.dirname(directory)).toBe(parent);await rm(directory,{recursive:true,force:true,maxRetries:8,retryDelay:100});}
});
