import {test,expect} from '@playwright/test';
import {mkdtemp,rm,realpath,readFile} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {unzipSync} from 'fflate';
import {encryptedFixture} from './encrypted-fixture.js';
import {sampleNotebook} from '../../src/sample.js';
import {ResearchMaterials} from '../../src/research-materials.js';
import {clearVault} from '../../src/encryption.js';
import {startServer} from '../../src/server.js';
import {readDatasetExchange} from '../../src/dataset-exchange-reader.js';
import {openEvidence} from './record-editor-helper.js';

test('export selected fields and observations, download the checked archive and retire the prepared copies',async({page})=>{
 test.setTimeout(180000);page.setDefaultTimeout(20000);
 const parent=await realpath(os.tmpdir()),directory=await mkdtemp(path.join(parent,'observanda-exchange-ui-')),book=sampleNotebook(),recordId=book.entries[0].id;
 let fixture,app;const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 try{
  fixture=await encryptedFixture(directory,book);const m=new ResearchMaterials(fixture.workspace);
  const width=20,labels=Array.from({length:width},(_,i)=>i===19?'Reference count':'Field '+(i+1));
  const source=Buffer.from(labels.join(',')+'\n'+[1,2,3].map(i=>labels.map((_,n)=>n===19?'900719925474099'+i:i+'-'+n).join(',')).join('\n'));
  const upload=await m.startImport({recordId,name:'field-counts.csv',size:source.length});await m.appendImport(upload.id,0,[source]);
  const artifact=await m.finishImport(upload.id);
  await m.dataset({recordId,title:'Retained survey counts',artifact,exclusions:{[artifact.id+':3']:'Instrument offline'}});
  app=await startServer({root:fixture.workspace.root,deviceStore:fixture.deviceStore,headless:true});await page.goto(app.url);await page.goto(app.origin+'/#/records/'+recordId);
  await page.getByRole('button',{name:'Evidence and results',exact:true}).click();
  await openEvidence(page);
  const dialog=page.locator('#dialog');
  await dialog.locator('.material-list li').filter({has:page.getByText('Retained survey counts',{exact:true})}).getByRole('button',{name:'Inspect',exact:true}).click();
  await dialog.getByRole('button',{name:'Export dataset',exact:true}).click();
  await dialog.getByLabel('Spreadsheet format').selectOption('tsv');
  await dialog.getByLabel('Rows',{exact:true}).selectOption('range');
  await dialog.getByLabel('First row',{exact:true}).fill('2');await dialog.getByLabel('Last row',{exact:true}).fill('3');
  await dialog.getByLabel('Include excluded observations and their reasons').uncheck();
  await dialog.getByLabel('Columns',{exact:true}).selectOption('selected');
  await dialog.getByRole('button',{name:'Next columns'}).click();await dialog.getByLabel('Reference count (20)').check();
  await dialog.getByRole('button',{name:'Prepare export'}).click();
  await expect(dialog.getByText('Your dataset export is ready.',{exact:true})).toBeVisible({timeout:90000});
  const pending=page.waitForEvent('download');await dialog.getByRole('button',{name:'Download ZIP'}).click();
  const transfer=await pending;expect(await transfer.failure()).toBeNull();
  const files=unzipSync(await readFile(await transfer.path()));
  expect(Buffer.from(files['dataset.tsv']).toString()).toBe('"Reference count"\r\n"9007199254740993"\r\n');
  let row;const complete=await readDatasetExchange([files['dataset.jsonl']],frame=>{if(frame.type==='row')row=frame.metadata;});
  expect(complete.rows).toBe(1);expect(complete.columns).toBe(1);expect(row.id).toBe(artifact.id+':4');
  await dialog.getByRole('button',{name:'Remove prepared files'}).click();
  await expect(dialog.getByText('The prepared export files have been removed.')).toBeVisible();
  await dialog.getByRole('button',{name:'Back to evidence',exact:true}).click();
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await page.goto(app.origin+'/#/records/'+book.entries[1].id);
  await expect(page.getByRole('heading',{name:book.entries[1].title,exact:true})).toBeVisible();
  if(!await page.getByRole('button',{name:'Open evidence & analysis',exact:true}).isVisible())await page.getByRole('button',{name:'Evidence and results',exact:true}).click();
  await openEvidence(page);
  await dialog.getByRole('button',{name:'Import original file',exact:true}).click();
  await dialog.getByLabel('Original file',{exact:true}).setInputFiles({name:'dataset.jsonl',mimeType:'application/x-ndjson',buffer:Buffer.from(files['dataset.jsonl'])});
  await dialog.getByRole('button',{name:'Import original',exact:true}).click();
  await dialog.locator('.material-list li').filter({hasText:'dataset.jsonl'}).getByRole('button',{name:'Inspect',exact:true}).click();
  await dialog.getByRole('button',{name:'Import typed dataset',exact:true}).click();
  await dialog.getByLabel('Dataset name').fill('Received observations');
  await dialog.getByRole('button',{name:'Import typed dataset',exact:true}).click();
  await expect(dialog.getByRole('heading',{name:'Received observations',exact:true})).toBeVisible({timeout:90000});
  const reading=dialog.getByRole('button',{name:'Inspect value: Reference count · 1',exact:true});
  await expect(reading).toHaveText('9007199254740993');
  await expect(reading).toHaveAccessibleDescription('9007199254740993');
  expect(errors).toEqual([]);
 }finally{
  await app?.close();if(fixture)await clearVault(fixture.vault);expect(path.dirname(directory)).toBe(parent);
  await rm(directory,{recursive:true,force:true,maxRetries:8,retryDelay:100});
 }
});
