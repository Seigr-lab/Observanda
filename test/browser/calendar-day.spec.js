import os from 'node:os';
import {encryptedFixture} from './encrypted-fixture.js';
import {clearVault} from '../../src/encryption.js';
import {test,expect} from '@playwright/test';
import {mkdtemp,rm} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {Workspace} from '../../src/storage.js';
import {sampleNotebook} from '../../src/sample.js';
import {workspaceModules} from '../../src/modules/index.js';
import {defaultDashboard} from '../../src/web/dashboard-model.js';
import {dashboardSnapshot} from '../../src/preferences.js';
import {writeWorkspaceDashboard} from '../../src/security/dashboard-storage.js';
import {startServer} from '../../src/server.js';

test.use({timezoneId:'Europe/Oslo',locale:'en-GB'});
test('calendar dates open a scoped day plan and create dated drafts without saving implicitly',async({page})=>{
 const directory=await mkdtemp(path.join(os.tmpdir(),'observanda-calendar-day-')),root=path.join(directory,'workspace'),book=sampleNotebook();
 book.projects[0].tools=['planning','resources'];
 const {workspace,vault,deviceStore}=await encryptedFixture(directory,book);const store=workspaceModules(workspace);
 const save=(type,id,data)=>store.execute({workspaceId:book.id,commandId:randomUUID(),action:type+'.save',payload:{id,expectedRevision:null,data}});
 const calendar=randomUUID(),otherCalendar=randomUUID(),equipment=randomUUID();
 await save('calendar',calendar,{name:'Studio',projectId:book.projects[0].id,color:'#3958ba',archived:false});
 await save('calendar',otherCalendar,{name:'Gallery',projectId:null,color:'#38786c',archived:false});
 const base={calendarId:calendar,allDay:true,timeZone:'Europe/Oslo',location:'Studio A',notes:'',status:'confirmed'};
 await save('event',randomUUID(),{...base,title:'Installation',startsAt:'2026-10-30',endsAt:'2026-11-02'});
 await save('event',randomUUID(),{...base,title:'Finished yesterday',startsAt:'2026-10-30',endsAt:'2026-10-31'});
 await save('event',randomUUID(),{...base,title:'Tomorrow only',startsAt:'2026-11-01',endsAt:'2026-11-02'});
 await save('event',randomUUID(),{...base,title:'Gallery programme',calendarId:otherCalendar,startsAt:'2026-10-31',endsAt:'2026-11-01'});
 await save('event',randomUUID(),{...base,title:'Late session',allDay:false,startsAt:'2026-10-30T23:30:00.000Z',endsAt:'2026-10-31T00:30:00.000Z'});
 await save('event',randomUUID(),{...base,title:'Ends at midnight',allDay:false,startsAt:'2026-10-30T21:00:00.000Z',endsAt:'2026-10-30T23:00:00.000Z'});
 await save('task',randomUUID(),{projectId:book.projects[0].id,title:'Send programme',description:'',status:'todo',priority:'normal',dueOn:'2026-10-31',assignees:[],checklist:[],dependencies:[],links:[]});
 await save('resource',equipment,{projectId:book.projects[0].id,name:'Mixing desk',code:'',kind:'equipment',description:'',categoryId:null,schemaRevision:null,fieldSchema:[],values:{},location:'Studio A',unit:'',capacity:1,status:'available',links:[]});
 await save('booking',randomUUID(),{projectId:book.projects[0].id,title:'Desk reservation',resourceId:equipment,startsAt:'2026-10-31T09:00:00.000Z',endsAt:'2026-10-31T10:00:00.000Z',timeZone:'Europe/Oslo',places:1,kind:'work',status:'confirmed',notes:'',links:[]});
 const settings=defaultDashboard(),preferencesFile=path.join(directory,'preferences.json');settings.enabledModules.push('planning','resources');
 await writeWorkspaceDashboard(workspace,settings,dashboardSnapshot(defaultDashboard()).etag);
 const app=await startServer({root,port:0,preferencesFile,deviceStore}),main=page.locator('#main'),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(app.url);
  await page.locator('#main-navigation [data-action="module-open"][data-module-id="planning"][data-module-path=""]').click();
  await page.getByLabel('Month',{exact:true}).fill('2026-10');
  const cell=main.locator('[data-calendar-day="2026-10-31"]');
  await expect(cell.getByRole('button',{name:/Late session/})).toBeVisible();
  await page.evaluate(()=>{window.keptNavigation=document.querySelector('#main-navigation');});
  // Double-click empty cell space, independently of the accessible date button.
  await cell.dblclick({position:{x:4,y:4}});
  await expect(main.locator('[data-day-heading]')).toContainText('31');
  await expect(page.getByLabel('Date',{exact:true})).toHaveValue('2026-10-31');
  const plan=main.locator('.calendar-day-plan');
  for(const title of ['Installation','Gallery programme','Late session','Send programme','Desk reservation'])await expect(plan.getByRole('button',{name:new RegExp(title)})).toBeVisible();
  await expect(plan).not.toContainText('Finished yesterday');
  await expect(plan).not.toContainText('Tomorrow only');
  await expect(plan).not.toContainText('Ends at midnight');
  await expect(plan.getByRole('button',{name:/Late session/})).toContainText('00:30');
  await expect(plan.getByRole('button',{name:/Desk reservation/})).toContainText('10:00');
  await main.locator('[data-calendar-source="'+otherCalendar+'"]').uncheck();
  await expect(plan).not.toContainText('Gallery programme');
  await expect(page.getByLabel('Date',{exact:true})).toHaveValue('2026-10-31');
  await page.getByLabel('Show location').selectOption(book.projects[0].id);
  await plan.getByRole('button',{name:/Late session/}).click();
  await expect(page.getByLabel('Event title',{exact:true})).toHaveValue('Late session');
  await main.getByRole('button',{name:'Calendars',exact:true}).click();
  await expect(page.getByLabel('Date',{exact:true})).toHaveValue('2026-10-31');
  await main.getByRole('button',{name:'Add event',exact:true}).click();
  await expect(page.getByLabel('Starts',{exact:true})).toHaveValue('2026-10-31');
  await expect(page.getByLabel('Ends (exclusive date)',{exact:true})).toHaveValue('2026-11-01');
  await expect(page.getByRole('button',{name:'Calendar',exact:true})).toHaveText('Studio');
  await page.getByLabel('Event title',{exact:true}).fill('Sound check');
  expect((await store.read()).entities.some(e=>e.data.title==='Sound check')).toBe(false);
  await page.getByLabel('All day',{exact:true}).uncheck();
  await expect(page.getByLabel('Starts',{exact:true})).toHaveValue('2026-10-31T09:00');
  await main.getByRole('button',{name:'Save event',exact:true}).click();
  await expect(main.locator('[data-module-status]')).toHaveText('Saved');
  await main.getByRole('button',{name:'Calendars',exact:true}).click();
  await expect(plan.getByRole('button',{name:/Sound check/})).toBeVisible();
  await main.getByRole('button',{name:'Add event',exact:true}).click();
  await page.getByLabel('Event title',{exact:true}).fill('Discard this');
  await main.getByRole('button',{name:'Discard edits',exact:true}).click();
  await main.getByRole('button',{name:'Calendars',exact:true}).click();
  expect((await store.read()).entities.some(e=>e.data.title==='Discard this')).toBe(false);
  await page.getByRole('button',{name:'Dismiss',exact:true}).click();
  await main.getByRole('button',{name:'Next day',exact:true}).click();
  await expect(page.getByLabel('Date',{exact:true})).toHaveValue('2026-11-01');
  await expect(plan.getByRole('button',{name:/Tomorrow only/})).toBeVisible();
  await expect(plan).not.toContainText('Sound check');
  await main.getByRole('button',{name:'Next day',exact:true}).click();
  await expect(plan).toContainText('No plans for this day');
  await main.getByRole('button',{name:'Back to month',exact:true}).click();
  const dateButton=main.locator('[data-command="calendar-open-day"][data-date="2026-11-02"]');
  await expect(dateButton).toBeFocused();
  await dateButton.press('Enter');
  await expect(page.getByLabel('Date',{exact:true})).toHaveValue('2026-11-02');
  await main.getByRole('button',{name:'Previous day',exact:true}).click();
  await main.getByRole('button',{name:'Previous day',exact:true}).click();
  await expect(plan.getByRole('button',{name:/Sound check/})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  const planBox=await plan.boundingBox(),sourcesBox=await main.locator('.calendar-sources').boundingBox();
  expect(planBox.y).toBeLessThan(sourcesBox.y);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  expect(await page.evaluate(()=>window.keptNavigation===document.querySelector('#main-navigation'))).toBe(true);
  expect(errors).toEqual([]);
 }finally{await app.close();clearVault(vault);await rm(directory,{recursive:true,force:true});}
});
