  await expect(link.getByLabel('Version to choose',{exact:true})).toBeDisabled();await expect(link.getByLabel('Version to choose',{exact:true})).toHaveValue('exact');
  await link.getByRole('button',{name:'Choose target',exact:true}).click();await link.getByRole('button',{name:/Colour comparison method/}).click();
  await link.getByRole('button',{name:'Save changes',exact:true}).click();await expect(link).not.toBeVisible();
  await expect.poll(async()=>(await current('Pigment stability')).relations.some(l=>l.role==='uses-method')).toBe(true);
  await (await activity('Add run or take')).click();await completeRunCreation(page,'Pigment run one');
  await value('status','Edit progress',form=>form.getByLabel('Progress',{exact:true}).selectOption('completed'));
  await value('outcome','Edit outcome',form=>form.getByLabel('Outcome',{exact:true}).fill('Negative result'));
  let first=await current('Pigment run one');const methodRevision=first.relations.find(l=>l.role==='uses-method').target.revision;
  expect(first.relations.find(l=>l.role==='run-of').target.id).toBe(experiment.id);expect(first.status).toBe('completed');expect(first.outcome).toBe('Negative result');
  await (await revealInEditor(page,page.getByRole('button',{name:'Create another run or take',exact:true}),'Evidence and results')).click();await completeRunCreation(page,'Pigment run two');
