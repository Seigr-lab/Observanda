import {test,expect} from '@playwright/test';
import {mkdtemp,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {Workspace} from '../../src/storage.js';
import {sampleNotebook} from '../../src/sample.js';
import {startServer} from '../../src/server.js';
import {buildPublication} from '../../src/publication.js';
import {contentBuffer} from '../../src/file-content.js';
test('investigation and creative take journeys retain methods, separate outcomes and stable links',async({page,browser})=>{
 test.setTimeout(120000);page.setDefaultTimeout(12000);
 await mkdir('.local/ux-review',{recursive:true});
 const directory=await mkdtemp(path.resolve('.local/ux-review/run-navigation-')),root=path.join(directory,'workspace'),book=sampleNotebook();
 const [experiment,method,series]=book.entries;
 experiment.type='experiment';experiment.title='Pigment stability';experiment.figures=[];experiment.body='Question: does the colour fade?';
 experiment.sections=[{id:randomUUID(),title:'Rationale',body:'Compare two papers under the same light.'},{id:randomUUID(),title:'Limitations',body:'Two runs are not a reliability study.'}];
 method.type='protocol';method.title='Colour comparison method';method.body='Keep the lamp at one metre.';method.share=false;
 series.title='Acoustic sessions';series.type='note';
 const ws=new Workspace(root);await ws.create(book);
 const app=await startServer({root,port:0,preferencesFile:path.join(directory,'preferences.json')}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const dialog=page.locator('#dialog');
 const save=async()=>{await page.locator('.section-save [data-action="save"]').click();await expect(page.locator('#save-status')).toHaveText('Saved');};
 try{
  await page.goto(app.url);await page.evaluate(id=>location.hash='#/notebooks/'+id,book.notebooks[0].id);
  await page.getByRole('searchbox',{name:'Search records',exact:true}).fill('Pigment');
  await page.getByRole('button',{name:'Pigment stability',exact:true}).click();
  await page.getByRole('button',{name:'Edit record',exact:true}).click();
  await page.getByRole('button',{name:'Link exact method',exact:true}).click();
  await expect(dialog.getByLabel('Reference version')).toBeDisabled();
  await expect(dialog.getByLabel('Reference version')).toHaveValue('exact');
  await dialog.getByRole('button',{name:/Colour comparison method/}).click();await save();
  await page.getByRole('button',{name:'Add run or take',exact:true}).click();
  await page.getByLabel('Record title',{exact:true}).fill('Pigment run one');
  await page.getByLabel('Progress',{exact:true}).selectOption('completed');
  await page.getByLabel('Outcome Optional',{exact:true}).fill('Negative result');
  await page.getByLabel('Include in website',{exact:false}).check();await save();
  let snapshot=await ws.read();const first=snapshot.book.entries.find(e=>e.title==='Pigment run one'),methodRevision=first.relations.find(l=>l.role==='uses-method').target.revision;
  expect(first.relations.find(l=>l.role==='run-of').target.id).toBe(experiment.id);
  await page.getByRole('button',{name:'Create another run or take',exact:true}).click();
  await expect(page).not.toHaveURL(new RegExp(first.id+'$'));
  await page.getByLabel('Record title',{exact:true}).fill('Pigment run two');
  await expect(page.getByLabel('Outcome Optional',{exact:true})).toHaveValue('');
  await page.getByLabel('Progress',{exact:true}).selectOption('incomplete');await save();
  snapshot=await ws.read();const second=snapshot.book.entries.find(e=>e.title==='Pigment run two');
  expect(second.share).toBe(false);expect(second.relations.find(l=>l.role==='uses-method').target.revision).toBe(methodRevision);
  snapshot.book.entries.find(e=>e.id===method.id).body='New method with a different lamp.';await ws.save(snapshot.book,snapshot.etag);
  await page.getByRole('button',{name:'Colour comparison method',exact:true}).click();
  await expect(dialog).toContainText('Keep the lamp at one metre.');await expect(dialog).not.toContainText('New method with a different lamp.');
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Read record',exact:true}).click();
  await expect(page.locator('.record-reader')).toContainText('incomplete');
  await page.getByRole('link',{name:'Pigment stability',exact:true}).click();
  await expect(page.locator('.run-list')).toContainText('Pigment run one');
  await expect(page.locator('.run-list')).toContainText('Pigment run two');
  await expect(page.locator('.run-list')).toContainText('Negative result');
  await page.getByText('Compare conditions and changes',{exact:true}).click();
  await expect(page.getByRole('region',{name:'Run comparison'})).toContainText(methodRevision.slice(0,12));
  await page.getByRole('button',{name:'Back to records',exact:true}).click();
  await expect(page.getByRole('searchbox',{name:'Search records',exact:true})).toHaveValue('Pigment');
  await expect(page.locator('.record-counts')).toContainText('1 experiment');
  await page.getByRole('button',{name:'Pigment stability',exact:true}).click();
  await page.getByRole('link',{name:'Rationale',exact:true}).click();
  await expect(page).toHaveURL(new RegExp('/read/'+experiment.sections[0].id+'$'));
  await expect(page.locator('#record-section-'+experiment.sections[0].id)).toBeFocused();
  await page.goBack();await expect(page).toHaveURL(new RegExp(experiment.id+'/read$'));
  await page.goForward();await expect(page).toHaveURL(new RegExp('/read/'+experiment.sections[0].id+'$'));
  await page.reload();await expect(page.locator('.record-reader h1')).toHaveText('Pigment stability');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.documentElement.style.setProperty('--app-font-size','24px'));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:path.join(directory,'reader-phone.png')});
  await page.emulateMedia({media:'print'});await expect(page.locator('.record-toolbar')).toBeHidden();
  await page.emulateMedia({media:'screen'});
  await page.getByRole('button',{name:'Edit record',exact:true}).focus();await page.keyboard.press('Enter');
  await expect(page.getByLabel('Record title',{exact:true})).toHaveValue('Pigment stability');
  await page.setViewportSize({width:1440,height:1000});await page.evaluate(()=>document.documentElement.style.removeProperty('--app-font-size'));
  await page.evaluate(id=>location.hash='#/records/'+id,series.id);
  await page.getByText('Organize runs or takes',{exact:true}).click();
  await page.getByRole('button',{name:'Add run or take',exact:true}).click();
  await page.getByLabel('Record title',{exact:true}).fill('Curtains closed take');
  await page.getByLabel('Outcome Optional',{exact:true}).fill('Warm, intimate sound');await save();
  await page.getByRole('button',{name:'Read record',exact:true}).click();
  await page.getByRole('link',{name:'Acoustic sessions',exact:true}).click();
  await expect(page.locator('.run-list')).toContainText('Curtains closed take');
  await expect(page.locator('.run-list')).toContainText('Warm, intimate sound');
  const output=buildPublication((await ws.read()).book);
  const context=await browser.newContext({javaScriptEnabled:false}),publicPage=await context.newPage();
  await publicPage.route('https://edition.invalid/section/**',async route=>{
   const key=new URL(route.request().url()).pathname.slice('/section/'.length),value=output.files.get(key);
   if(value===undefined)return route.fulfill({status:404,body:'Missing'});
   return route.fulfill({status:200,contentType:key.endsWith('.html')?'text/html':key.endsWith('.css')?'text/css':'application/octet-stream',body:typeof value==='string'?value:await contentBuffer(value)});
  });
  await publicPage.goto('https://edition.invalid/section/entries/'+experiment.id+'.html');
  await publicPage.getByRole('link',{name:'Pigment run one',exact:true}).click();
  await expect(publicPage).toHaveURL(new RegExp(first.id+'.html$'));
  await expect(publicPage.locator('.record-page')).toContainText('Negative result');
  await publicPage.getByRole('link',{name:'Pigment stability',exact:true}).click();
  await expect(publicPage.locator('body')).not.toContainText('Pigment run two');
  await expect(publicPage.locator('body')).not.toContainText('Colour comparison method');
  await context.close();expect(errors).toEqual([]);
 }finally{await app.close();}
});
