test('removing the only page returns to an empty website, with undo and discard before saving',async({page})=>{
 await open(page,createNotebook('Studio'));
 await createHome(page).click();
 await page.getByLabel('Homepage introduction',{exact:true}).fill('Keep this authored introduction');
 await save(page);
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Remove homepage',exact:true}).click();
 await expect(page.locator('#website-preview-empty')).toBeVisible();
 await expect(createHome(page)).toBeVisible();
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 await expect(page.getByLabel('Homepage introduction',{exact:true})).toHaveValue('Keep this authored introduction');
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Remove homepage',exact:true}).click();
 await page.getByRole('button',{name:'Discard changes',exact:true}).click();
 await expect(page.locator('#website-preview-page')).toHaveValue('index.html');
 await openPageSettings(page);await expect(page.getByLabel('Homepage introduction',{exact:true})).toHaveValue('Keep this authored introduction');
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Remove homepage',exact:true}).click();
 await save(page);await page.reload();
 await expect(page.locator('#website-preview-empty')).toBeVisible();
 expect((await new Workspace(root).read()).book.website.home.enabled).toBe(false);
 expect(errors).toEqual([]);
});
