import {test,expect} from '@playwright/test';
import {mkdtemp,mkdir} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {startServer} from '../../src/server.js';
import {Workspace} from '../../src/storage.js';
import {createNotebook} from '../../src/model.js';
import {sampleNotebook} from '../../src/sample.js';
import {task,openPageSettings} from './composer-helper.js';
import {navigate} from './preferences-helper.js';
let app,root,errors;
const frame=page=>page.frameLocator('#website-draft-preview');
const createHome=page=>page.locator('.canvas-toolbar [data-action=website-create-home]');
const save=async page=>{await page.getByRole('button',{name:'Save website',exact:true}).click();await expect(page.locator('#save-status')).toHaveText('Saved');};
async function open(page,book){
 root=await mkdtemp(path.join(os.tmpdir(),'observanda-optional-home-'));await new Workspace(root).create(book);
 app=await startServer({root,preferencesFile:path.join(root,'preferences.json'),port:0});
 errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto(app.url);await navigate(page,'Website editor');
}
test.afterEach(async()=>{await app?.close();});
test('create and remove Home explicitly, retain site identity, undo and review a standalone page',async({page})=>{
 test.setTimeout(60000);
 await open(page,createNotebook('Collective','Private workspace description'));
 await expect(page.locator('#website-preview-empty')).toBeVisible();
 await expect(page.locator('#website-preview-page option')).toHaveText(['No pages yet']);
 await expect(page.locator('#website-preview-status')).toBeEmpty();
 await page.getByRole('button',{name:'Add page',exact:true}).click();
 await page.getByLabel('Page title',{exact:true}).fill('Listening notes');
 await expect(frame(page).getByRole('heading',{name:'Listening notes',exact:true})).toBeVisible();
 await save(page);await page.reload();
 await expect(page.locator('#website-preview-page option')).toHaveText(['Listening notes']);
 await createHome(page).click();
 await expect(page.locator('#website-preview-page')).toHaveValue('index.html');
 await expect(page.locator('#website-preview-page option').first()).toHaveText('Home');
 await expect(page.getByLabel('Website title',{exact:true})).toHaveCount(0);
 await page.getByLabel('Homepage heading',{exact:true}).fill('Welcome to our work');
 await page.getByLabel('Homepage introduction',{exact:true}).fill('An introduction just for Home');
 await task(page,'Site');
 await page.getByLabel('Website title',{exact:true}).fill('Public collective');
 await task(page,'Page');await page.getByLabel('Editing area',{exact:true}).selectOption('footer');
 await page.getByLabel('Footer text',{exact:true}).fill('Made together');
 await page.getByLabel('Editing area',{exact:true}).selectOption('body');
 await expect(frame(page).locator('.site-name')).toHaveText('Public collective');
 await expect(frame(page).getByRole('heading',{name:'Welcome to our work'})).toBeVisible();
 await save(page);await page.reload();await openPageSettings(page);
 await expect(page.getByLabel('Homepage introduction')).toHaveValue('An introduction just for Home');
 const remove=async()=>{page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Remove homepage',exact:true}).click();};
 await remove();await expect(page.locator('#website-preview-page option')).toHaveText(['Listening notes']);
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 await expect(page.locator('#website-preview-page')).toHaveValue('index.html');
 await expect(page.getByLabel('Homepage introduction')).toHaveValue('An introduction just for Home');
 await remove();await save(page);await page.reload();
 const saved=(await new Workspace(root).read()).book;
 expect(saved.title).toBe('Collective');expect(saved.website.title).toBe('Public collective');expect(saved.website.home.enabled).toBe(false);
 await page.getByRole('button',{name:'Preview & export',exact:true}).click();await page.getByRole('button',{name:'Prepare selected edition',exact:true}).click();
 await expect(page.locator('#preview-page option')).toHaveText(['Listening notes']);
 await expect(page.frameLocator('iframe[title="Publication preview"]').getByRole('heading',{name:'Listening notes',exact:true})).toBeVisible();
 const url=await page.getByRole('link',{name:'Open full preview',exact:true}).getAttribute('href');
 const manifest=await (await page.request.get(app.origin+'/preview/'+url.split('/')[2]+'/publication.json')).json();
 expect(manifest.files.map(f=>f.path)).not.toContain('index.html');
 expect(errors).toEqual([]);
});
