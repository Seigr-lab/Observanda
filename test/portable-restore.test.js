import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,rename,readFile,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {ResearchMaterials} from '../src/research-materials.js';
import {contentBuffer} from '../src/file-content.js';
import {websiteVersions} from '../src/website-versions.js';
import {WebsiteFileStore} from '../src/website-file-store.js';
import {updateWorkspaceAccess,workspaceAccess} from '../src/security/workspace-access.js';
import {TestDeviceStore} from './device-fixture.js';
import {readAccess,verifyAccess} from '../src/access.js';
import {encryptedFixture} from './browser/encrypted-fixture.js';
import {sampleNotebook} from '../src/sample.js';
import {clearVault} from '../src/encryption.js';
import {Workspace} from '../src/storage.js';
import {WorkspaceProjectCopy} from '../src/workspace-project-copy.js';
import {WorkspaceCopyRecovery} from '../src/workspace-copy-recovery.js';
import {PortableBackupHistory} from '../src/portable-backup-history.js';
import {restorePortable} from '../src/portable-restore.js';
import {CATALOGUE_ARCHIVE} from '../src/postgres-activation.js';

test('recheck and restore a moved independent backup after the source is unavailable',async t=>{
 const directory=await mkdtemp(path.join(os.tmpdir(),'observanda-restore-test-'));
 const f=await encryptedFixture(directory,sampleNotebook());
 t.after(async()=>{await clearVault(f.vault);await rm(directory,{recursive:true,force:true,maxRetries:8,retryDelay:100});});
 const original=path.join(directory,'backup'),moved=path.join(directory,'removable'),destination=path.join(directory,'restored');
 const changeRecovery=async()=>{
  const {etag}=await workspaceAccess(f.workspace.root,f.vault,{deviceStore:f.deviceStore});
  return updateWorkspaceAccess(f.workspace.root,f.vault,{action:'recovery',etag,confirmed:true},{deviceStore:f.deviceStore});
 };
 const previousKey=await changeRecovery();
 const originalRecord=await f.workspace.read();
 const changed=await f.workspace.update(book=>{book.entries[0].body='Final measured observation';return book;});
 const records=await f.workspace.history();
 const materials=new ResearchMaterials(f.workspace),pixels=await readFile(new URL('../src/preview-assets/image.png',import.meta.url));
 const upload=await materials.startImport({recordId:changed.book.entries[0].id,name:'field-camera.png',size:pixels.length});
 await materials.appendImport(upload.id,0,[pixels]);const artifact=await materials.finishImport(upload.id);
 const siteId=randomUUID(),site=new WebsiteFileStore(f.workspace);
 let page=await site.create({id:siteId,name:'Field report'});
 page=await site.save(siteId,{...page,expectedRevision:page.site.revision,html:page.html.replace('</main>','<p>Preliminary estimate</p></main>'),css:'p{color:navy}'});
 page=await websiteVersions(site,siteId,'name',{label:'Review edition',expectedRevision:page.site.revision});
 const named=(await websiteVersions(site,siteId,'list',{expectedRevision:page.site.revision})).items.find(row=>row.label==='Review edition');
 page=await site.save(siteId,{...page,expectedRevision:page.site.revision,html:page.html.replace('Preliminary estimate','Corrected estimate'),css:'p{color:teal}'});
 const interruption=new WorkspaceProjectCopy(f.workspace,{checkpoint:async stage=>{
  if(stage==='workspace-published')throw Error('Stopped before the completion marker was removed');
 }});
 await assert.rejects(interruption.exportPortable(original),/Stopped before the completion marker/);
 const copy=new WorkspaceCopyRecovery(f.workspace,original);
 await assert.rejects(copy.portableCompletion(),{code:'STORAGE_INCOMPLETE'});
 const archiveFile=path.join(original,CATALOGUE_ARCHIVE),snapshot=await readFile(archiveFile);
 await writeFile(archiveFile,snapshot.subarray(0,-1));
 await assert.rejects(new WorkspaceProjectCopy(f.workspace).exportPortable(original),{code:'STORAGE_COPY'});
 await assert.rejects(copy.portableCompletion(),{code:'STORAGE_INCOMPLETE'});
 await writeFile(archiveFile,snapshot);
 await new WorkspaceProjectCopy(f.workspace).exportPortable(original);
 const receipt=await copy.portableCompletion();
 assert.ok(receipt.inventory.files>0);
 const history=new PortableBackupHistory(path.join(directory,'preferences.json'),f.workspace);
 await history.remember(original,receipt);assert.equal((await history.read()).backup.id,receipt.id);
 const checked=await copy.verifyPortable(receipt.id);
 assert.deepEqual(checked.inventory,receipt.inventory);
 await history.remember(original,checked);
 const currentKey=await changeRecovery();
 await rename(f.workspace.root,path.join(directory,'source-unavailable'));await rename(original,moved);
 const backup=new Workspace(moved,f.vault),archive=path.join(moved,CATALOGUE_ARCHIVE),bytes=await readFile(archive);
 await writeFile(archive,bytes.subarray(0,-1));
 await assert.rejects(restorePortable(backup,destination,{expectedId:receipt.id}),{code:'STORAGE_COPY'});
 await writeFile(archive,bytes);
 const options={expectedId:receipt.id,deviceStore:f.deviceStore};
 const restored=await restorePortable(backup,destination,options);
 assert.notEqual(restored.restoredInventory.sha256,receipt.inventory.sha256);
 assert.equal(restored.restoredInventory.files,receipt.inventory.files);
 assert.deepEqual(await readFile(path.join(destination,CATALOGUE_ARCHIVE)),bytes);
 assert.equal((await restorePortable(backup,destination,options)).restoredAt,restored.restoredAt);
 assert.deepEqual(await readFile(archive),bytes);
 await history.restored(moved,restored);
 assert.equal((await history.read()).restoration.destination,destination);
 const fresh=new TestDeviceStore({file:path.join(directory,'new-device-key')});
 const access=await readAccess(destination,{deviceStore:fresh});
 await assert.rejects(verifyAccess(access,'','',{deviceStore:fresh,recovery:previousKey.recovery}),{code:'ACCESS_DENIED'});
 const key=await verifyAccess(access,'','',{deviceStore:fresh,recovery:currentKey.recovery});
 try{
  const independent=new Workspace(destination,key),site=new WebsiteFileStore(independent);
  assert.deepEqual(await independent.read(),changed);assert.deepEqual(await independent.history(),records);
  assert.deepEqual(await independent.readRevision(originalRecord.etag),originalRecord.book);
  assert.deepEqual(await contentBuffer((await new ResearchMaterials(independent).artifact(artifact)).content),pixels);
  const latest=await site.open(siteId);
  assert.equal(latest.html,page.html);assert.equal(latest.css,page.css);
  const comparison=await websiteVersions(site,siteId,'compare',{expectedRevision:latest.site.revision,version:named.id});
  assert.match(comparison.difference.before,/Preliminary estimate/);
  assert.match(comparison.difference.after,/Corrected estimate/);
 }finally{await clearVault(key);}
});
