import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes,randomUUID} from 'node:crypto';
import {mkdtemp,mkdir,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {Workspace} from '../src/storage.js';
import {WebsiteFileStore} from '../src/website-file-store.js';
import {websiteBreakpoints} from '../src/website-breakpoints.js';
import {closeIdleMutationFiles} from '../src/mutation-files.js';
import {defaultBreakpoints,layoutStart,layoutEnd,orderedLayoutLines,validBreakpoints} from '../src/web/website-breakpoint-model.js';
import {websitePageDesigns} from '../src/website-page-designs.js';
import {websiteSiteLifecycle} from '../src/website-site-lifecycle.js';

test('review overlapping ranges, reject stale order and preserve authored rules and independently owned design copies',async t=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'observanda-scientific-layout-'));await mkdir(path.join(root,'.observanda'));
 t.after(async()=>{await closeIdleMutationFiles();await rm(root,{recursive:true,force:true,maxRetries:10});});
 const ws=new Workspace(root,{id:randomUUID(),key:randomBytes(32)}),store=new WebsiteFileStore(ws),id=randomUUID();
 ws.openCatalogue=ws.catalogue=()=>assert.fail('Layout opened research storage');
 const narrow={id:randomUUID(),name:'Instrument grid',min:null,max:1100},overlap={id:randomUUID(),name:'Plot annotations',min:980,max:1140};
 const ranges=[...defaultBreakpoints(),narrow,overlap],reverse=[...defaultBreakpoints(),overlap,narrow];
 assert.equal(validBreakpoints(ranges),true);assert.equal(validBreakpoints([...ranges,{...narrow,id:randomUUID()}]),false);
 const section='ow-layout-'+randomUUID(),foreign='ow-layout-'+randomUUID();
 const raw='@media print {figure {break-inside:avoid}}\n@container plots (min-width: 30rem) {'+layoutStart(foreign)+'.legend::before{content:"manual"}'+layoutEnd(foreign)+'}\n';
 const manual=layoutStart(foreign)+'@supports (display: grid) {.map {display:grid}}'+layoutEnd(foreign);
 const declarations=new Map([[narrow.id,'order: 1; gap: clamp(4px, 2vw, 32px);'],[overlap.id,'order: 2; visibility: hidden;']]);
 const css=order=>raw+manual+layoutStart(section)+orderedLayoutLines(declarations,section,order)+layoutEnd(section);
 const html='<html><head><title>Figures</title><link rel="stylesheet" href="style.css"></head><body><main><section class="'+section+'"><h2>Board</h2></section></main></body></html>';
 let page=await store.importFiles(id,{name:'Atlas',files:new Map([['index.html',html],['style.css',css(ranges)]])});
 const edit=(order,plan)=>websiteBreakpoints(store,id,{path:'index.html',expectedRevision:page.site.revision,ranges:order,reviewId:plan?.reviewId},Boolean(plan));
 const initial=await edit(ranges);assert.equal(initial.changed,0);page=await edit(ranges,initial);
 const oldPlan=await edit(reverse);assert.equal(oldPlan.changed,1);assert.equal(oldPlan.manual,1);
 page=await store.save(id,{path:'index.html',html:page.html.replace('Board','Figure board'),css:page.css,expectedRevision:page.site.revision});
 await assert.rejects(edit(reverse,oldPlan),{code:'CONFLICT'});
 page=await edit(reverse,await edit(reverse));assert.equal(page.css,css(reverse));assert.deepEqual(page.site.breakpoints,reverse);
 page=await websitePageDesigns(store,id,{path:'index.html',expectedRevision:page.site.revision,action:'name',name:'Figure board'});
 const {items:[design]}=await websitePageDesigns(store,id,{action:'list',path:'index.html',expectedRevision:page.site.revision});
 page=await websitePageDesigns(store,id,{action:'use',path:'index.html',expectedRevision:page.site.revision,design:design.id,title:'Second board',destination:'boards/b.html',inclusion:'included',labels:{text:'Text',heading:'Heading',image:'Image'}});
 const clone=page.html.match(/ow-layout-[a-f0-9-]{36}/)?.[0];assert.ok(clone);assert.notEqual(clone,section);
 assert.ok(page.css.includes(orderedLayoutLines(declarations,clone,reverse)));assert.ok(!page.css.includes(manual));
 const copyId=randomUUID(),args={action:'duplicate',copyId,title:'Remote lab',expectedRevision:page.site.revision};
 const review=await websiteSiteLifecycle(store,id,args);
 const copied=await websiteSiteLifecycle(store,id,{...args,reviewId:review.reviewId},true);
 assert.deepEqual(copied.site.breakpoints,reverse);assert.equal(copied.css,css(reverse));
 const dropped=reverse.filter(r=>r.id!==overlap.id),removal=await edit(dropped);
 assert.equal(removal.changed,2);page=await edit(dropped,removal);
 assert.equal(page.css,css(dropped));const other=await store.open(id,{path:'boards/b.html'});
 assert.ok(other.css.includes(orderedLayoutLines(declarations,clone,dropped)));assert.ok(!other.css.includes(overlap.id));
});
