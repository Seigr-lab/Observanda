test('default site converts its destination, confirmed deployment and folder ownership to file-only metadata', {timeout:180000},async t=>{
 const temporary=await realpath(os.tmpdir()),directory=await mkdtemp(path.join(temporary,'website-publish-migration-'));
 const book=upgradeNotebook(sampleNotebook());
 book.entries=[];
 let fixture;
 t.after(async()=>{
  await closeIdleMutationFiles();if(fixture)await clearVault(fixture.vault);
  assert.equal(path.dirname(directory),temporary);assert.ok(path.basename(directory).startsWith('website-publish-migration-'));
  await rm(directory,{recursive:true,force:true,maxRetries:10,retryDelay:100});
 });
 fixture=await encryptedFixture(directory,book);
 const {workspace}=fixture;
 const registry=await workspace.catalogue(readWebsiteDocumentRegistry);
 const id=registry.defaultSiteId,source=websiteWorkspace(workspace,null),store=new WebsiteFileStore(workspace);
 const publisher=new Publisher(workspace.root,{workspace:source});
 const config=defaultPublishing();Object.assign(config.github,{owner:'test-org',repository:'site',directory:'public'});
 const {destinationKey:key,etag}=await publisher.save(config,'new');
 const receipt={commit:'b'.repeat(40),releaseId:'c'.repeat(64),at:new Date().toISOString(),status:'uploaded-repository-only',
  manifestHash:'a'.repeat(64),manifestBytes:235,manifestFiles:1};
 const row={path:'public/index.html',mode:'100644',type:'blob',sha:'d'.repeat(40)};
 const built=new GithubPlanIndex(source,{version:1,collections:{entries:null}});
 await built.add('entries',row.path,row);
 const document=await built.finish();
 const folder=path.join(directory,'export'),ownerName='.observanda/local-exports/owners/'+digest(process.platform==='win32'?folder.toLowerCase():folder)+'.json';
 const file={path:'index.html',sha256:'e'.repeat(64),bytes:17},owner={version:1,directory:folder,files:[file],releaseId:receipt.releaseId,pending:null};
 const save=(name,value)=>source.writeMetadata(name,serialize(value));
 const pending=randomUUID(),deploymentFile='.observanda/deployment-active/'+key+'.json';
 await workspace.withLock(async()=>{
  await save('.observanda/publishing-ownership/'+key+'.json',{version:2,document,repositoryId:1234,commit:receipt.commit,releaseId:receipt.releaseId});
  await save('.observanda/publication-live/'+key+'.json',{version:1,commit:receipt.commit,releaseId:receipt.releaseId,files:['index.html'],removed:['withdrawn.html']});
  await save('.observanda/publishing-receipts.json',{[key]:receipt,['0'.repeat(64)]:{private:'unrelated'}});
  await save(ownerName,owner);
  await save(deploymentFile,{id:pending});
  await save('.observanda/deployments/'+pending+'.json',{id:pending,scope:registry.workspaceId,intent:{key,config},journal:{pushAttempted:true}});
  await save('.observanda/jobs/'+pending+'.json',{id:pending,type:'publication.deploy',scope:registry.workspaceId,state:'running',input:{websiteId:null}});
 });
 const convert=target=>store.scope(()=>workspace.withLock(async()=>{
  await source.lockWebsite();
  await migrateWebsitePublishingMetadata(source,store,target);
  await store.create({id:target,name:'Saved site'});
 }),{write:true});
 await assert.rejects(convert(randomUUID()),{code:'PUBLISH_OWNERSHIP'});
 await assert.rejects(convert(id),{code:'PUBLISH_PENDING'});
 assert.deepEqual((await store.list()).items,[]);
 await workspace.withLock(()=>source.removeMetadata(deploymentFile));
 await convert(id);
 await assert.rejects(convert(id),{code:'CONFLICT'});
 workspace.catalogue=()=>assert.fail('Research database reopened');
 assert.equal((await store.list()).items[0].id,id);
 const target=websitePublicationMetadata(store.publicationWorkspace(id)),standalone=new Publisher(workspace.root,{workspace:target});
 const saved=await standalone.read();
 assert.deepEqual(saved.config,config);assert.equal(saved.etag,etag);assert.deepEqual(saved.receipt,receipt);
 assert.deepEqual(Object.keys(JSON.parse(await target.readMetadata('.observanda/publishing-receipts.json'))),[key]);
 const imported=await readGithubOwnership(standalone,config,saved.receipt);
 assert.equal(imported.repositoryId,1234);assert.deepEqual(await new GithubPlanIndex(target,imported.document).get('entries',row.path),row);
 const inventory=await deploymentInventory(target,key);
 assert.deepEqual(await Array.fromAsync(deploymentInventoryPaths(target,inventory,'removed')),['withdrawn.html']);
 const local=JSON.parse(await target.readMetadata(ownerName));
 assert.deepEqual(await new LocalExportManifest(target).find(local.files,'index.html'),file);
 assert.equal(await target.deploymentOwnerId(),registry.workspaceId);
 assert.equal(await target.readMetadata('.observanda/jobs/'+pending+'.json'),null);
 assert.equal(await target.readMetadata('.observanda/deployments/'+pending+'.json'),null);
});
